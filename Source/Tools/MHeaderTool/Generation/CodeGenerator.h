    // 从 MFuture<TResult<T, E>> 中提取 T（原始响应类型）
    MString ExtractResponseType(const MString& returnType) const
    {
        // Strip SFutureResult<X> / MFuture<TResult<X, Y>> wrappers (and any
        // combination), returning the raw response type X. Used by the
        // generated ServerCall handler so it can call the typed method and
        // pattern-match on `TResult<RespType, FAppError>`.
        const MString sfPrefix = "SFutureResult<";
        const MString mfPrefix  = "MFuture<TResult<";

        MString T = returnType;
        // Outer wrapper: SFutureResult<Inner>
        if (T.rfind(sfPrefix, 0) == 0 && T.back() == '>')
        {
            MString Inner = T.substr(sfPrefix.size(), T.size() - sfPrefix.size() - 1);
            return ExtractResponseType(Inner);
        }
        // Inner wrapper: MFuture<TResult<X, Y>>
        if (T.rfind(mfPrefix, 0) == 0 && T.back() == '>')
        {
            MString Inner = T.substr(mfPrefix.size(), T.size() - mfPrefix.size() - 1);
            size_t comma = Inner.find(',');
            if (comma != MString::npos)
            {
                return Inner.substr(0, comma);
            }
        }
        return T;
    }

    // P3 SPEC §6.3 HARD RULE: a non-Async function declared inside MCLASS may
    // NOT use AWAIT_OK. Emit a compile-time gate that the user will see at
    // build time. Async-without-AWAIT_OK is OK (handled by the existing
    // GenerateServerCallHandler pending branch — see line 731).
    void GenerateAwaitOkValidation(
        std::ostringstream& out,
        const SParsedClass& parsedClass,
        const SParsedFunction& func) const
    {
        if (func.bIsAsync) return;
        if (ScanAwaitOkSites(func.AsyncBody).empty()) return;
        out << "// " << parsedClass.Name << "::" << func.Name
            << " — ERROR — non-Async function uses AWAIT_OK; spec 2026-07-24 §6.3.\n";
        out << "static_assert(true == false, \"P3: " << parsedClass.Name
            << "::" << func.Name << " uses AWAIT_OK but is not MFUNCTION(ServerCall, Async); see spec §6.3.\");\n";
    }

    // =========================================================================
    // P3: AWAIT_OK scanner + state machine generator
    // =========================================================================
    //
    // v1 scope (mirrors spec 2026-07-24 §7.3 subset):
    //   - Async functions may carry 0 or 1 AWAIT_OK statements at the top level.
    //     0 AWAIT_OKs is still allowed if the function's pending behavior comes
    //     from a ready SFutureResult<RespType>; that path is handled by the
    //     existing GenerateServerCallHandler pending branch.
    //   - 2+ AWAIT_OKs in a single Async function = static_assert error (P4 lifts).
    //   - Non-Async function with AWAIT_OK = static_assert error (spec §6.3).
    //   - AWAIT_OK(expr) where <expr> may contain arbitrary balanced ()s.
    // Each match becomes a single state slot in the generated Frame.
    // P3 v1 (spec §7.3 subset): ScanAwaitOkSites reports *how many* AWAIT_OK
    // sites appear at the top level of the user's inline body. Generator uses
    // only the count: 0 = no Frame, 1 = Frame helper, >=2 = static_assert.
    // (P4 lifts this to a multi-state Frame that slices body around sites.)
    struct SAwaitSite
    {
        size_t ExprStart = 0;       // byte offset of <expr> in AsyncBody
        size_t ExprEnd = 0;         // byte offset just after <expr> (past ')')
        MString Expr;           // captured <expr> text (verbatim)
    };

    // Find AWAIT_OK statements (statement-level only). Walks past balanced
    // parens so that "AWAIT_OK(fn(a,b))" counts as one site, not three.
    TVector<SAwaitSite> ScanAwaitOkSites(const MString& Body) const
    {
        TVector<SAwaitSite> Sites;
        const MString Needle = "AWAIT_OK(";
        size_t SearchPos = 0;
        while ((SearchPos = Body.find(Needle, SearchPos)) != MString::npos)
        {
            size_t ExprStart = SearchPos + Needle.size();
            int Depth = 1;
            size_t i = ExprStart;
            while (i < Body.size() && Depth > 0)
            {
                char ch = Body[i];
                if (ch == '(') ++Depth;
                else if (ch == ')')
                {
                    if (Depth == 1) break;
                    --Depth;
                }
                ++i;
            }
            if (Depth != 1 || i >= Body.size())
            {
                return {};   // malformed: caller will report
            }
            SAwaitSite Site;
            Site.ExprStart = ExprStart;
            Site.ExprEnd = i;
            Site.Expr = Body.substr(ExprStart, i - ExprStart);
            Sites.push_back(std::move(Site));
            SearchPos = i + 1;
        }
        return Sites;
    }

    // Emit the Frame struct + Run() entry for an Async function with a state
    // machine wrapping the user body. For zero-await Async functions this is a
    // no-op (no Frame is needed; SFutureResult pending already handled by
    // GenerateServerCallHandler pending branch).
    void GenerateAsyncStateMachine(
        std::ostringstream& out,
        const SParsedClass& parsedClass,
        const SParsedFunction& func) const
    {
        if (!func.bIsAsync) return;
        if (func.Params.empty()) return;

        const MString FrameName =
            "MHeaderTool_AsyncFrame_" + SanitizeIdentifier(parsedClass.Name) +
            "_" + SanitizeIdentifier(func.Name);
        const MString ReqType = func.Params[0].StorageType;
        const MString RespType = ExtractResponseType(func.ReturnStorageType);

        TVector<SAwaitSite> AwaitSites = ScanAwaitOkSites(func.AsyncBody);
        if (AwaitSites.empty())
        {
            // Zero-AWAIT_OK Async: function body has no `AWAIT_OK(...)` calls.
            // The Frame is unused in the user's body path; the existing
            // GenerateServerCallHandler ready/pending branch covers this case.
            // User's body — when eventually inline — would just `return MakeShared<...>`
            // of a ready SFutureResult, with no Frame interaction.
            out << "// " << FrameName
                << ": Async function with zero AWAIT_OK — no state machine emitted\n";
            out << "// (ServerCall handler bridges ready/pending SFutureResult already.)\n\n";
            return;
        }
        if (AwaitSites.size() > 1)
        {
            out << "// " << FrameName << ": ERROR — P3 v1 supports at most 1 AWAIT_OK per Async function,\n";
            out << "// this function has " << AwaitSites.size() << ". See spec 2026-07-24 §7.3.\n";
            out << "static_assert(true == false, \"P3 v1: Async function '" << func.Name
                << "' has " << AwaitSites.size() << " AWAIT_OK; max 1. See spec §7.3.\");\n\n";
            return;
        }

        // (P3 v1 supports exactly 1 AWAIT_OK site in inline body; sites[0] is
        //  referenced by no codegen path under the inline-body design — the
        //  user's body compiles verbatim, AwaitOk is the helper API.)

        // P3 v1 (spec 2026-07-24 §7.3): inline-body design. The user writes
        // the Async body inline in their header (a self-contained block that
        // constructs the Frame, sets Context/Service/Request, and uses the
        // AWAIT_OK macro to await one expression). The generator emits ONLY
        // the Frame helper struct; user body itself compiles normally and
        // drives dispatch. No `Run()` entry — the ServerCall handler just
        // calls TypedObject->Func(Request) and the user's body shapes the
        // SFutureResult path. No `Awaits=...` metadata — the await target
        // lives in the user's expression text, not in the macro.
        //
        // The Frame struct is emitted into a separate `<Class>_AsyncFrames.h`
        // file (see EmitAsyncFramesHeader). The user header must include that
        // file AFTER the headers defining ReqType/RespType/FAppError, so all
        // referenced types are already complete by the time the Frame struct
        // is parsed.

        // The Frame struct references ReqType / RespType / FAppError as
        // template arguments and members; its `SFutureResult<...>` member
        // forces `TOptional<TResult<T,E>>` (Promise state) to be
        // instantiated, which requires complete types at this point.
        //
        // For inline-body sites, the user header's own #include chain
        // transitively pulls in these types BEFORE the AsyncFrames header
        // is included. For direct consumers of AsyncFrames (unit tests,
        // other translation units), we emit explicit includes so the
        // header is self-contained. (The generated message headers do not
        // include the user header back, so this is safe — no circular
        // include.)
        EmitGeneratedTypeInclude(out, ReqType);
        EmitGeneratedTypeInclude(out, RespType);
        EmitGeneratedTypeInclude(out, "FAppError");

        // Forward-declare parsedClass.Name so the Frame can hold a pointer
        // to it (Service field). The class itself is defined later in the
        // user header, so we don't need its full definition here.
        EmitForwardDeclaration(out, parsedClass.Name);

        out << "// " << FrameName << ": Async frame helper (P3 v1, spec §7.3)\n";
        out << "//   User body constructs Frame, sets Service/Request/Ctx,\n";
        out << "//   returns AWAIT_OK(expr). AWAIT_OK -> Frame->AwaitOk(expr).\n";
        out << "//   AwaitOk is pass-through: returns Awaited verbatim so user\n";
        out << "//   body `return AWAIT_OK(expr)` matches the SF<Resp> signature.\n";
        out << "struct " << FrameName << "\n";
        out << "{\n";
        out << "    // Context (populated by user body)\n";
        out << "    MAsync::MAsyncContext* Ctx = nullptr;\n";
        out << "    " << parsedClass.Name << "* Service = nullptr;\n";
        out << "    " << ReqType << " Request;\n";
        out << "    // Single-await slot (P4 will split into per-state slots)\n";
        out << "    SFutureResult<" << RespType << "> AwaitedSlot;\n";
        out << "    " << RespType << " StoredValue {};\n";
        out << "\n";
        out << "    // AwaitOk — concrete-type entry used by the AWAIT_OK macro.\n";
        out << "//     Pass-through: returns Awaited so user body can write\n";
        out << "//     `return AWAIT_OK(expr);`. Records the awaitable in AwaitedSlot\n";
        out << "//     and snapshots the value into StoredValue (P4 state machine\n";
        out << "//     will read these; v1 just records).\n";
        out << "    SFutureResult<" << RespType
            << "> AwaitOk(SFutureResult<" << RespType << "> Awaited)\n";
        out << "    {\n";
        out << "        AwaitedSlot = Awaited;\n";
        out << "        if (Awaited.IsReady())\n";
        out << "        {\n";
        // Snapshot via IsOk/GetValue on the TResult reference, NOT via
        // MFuture::Get() which MOVES the value out of the shared state.
        // Awaited must remain valid for the caller's return path
            // (`return AWAIT_OK(expr);` passes Awaited back unchanged).
        out << "            const auto& R = Awaited.PeekResult();\n";
        out << "            if (R.IsOk()) StoredValue = R.GetValue();\n";
        out << "        }\n";
        out << "        else\n";
        out << "        {\n";
        out << "            Awaited.Then([this](MFuture<TResult<" << RespType
            << ", FAppError>> /*F*/)\n";
        out << "            {\n";
        out << "                if (!AwaitedSlot.IsReady()) return;\n";
        // Use PeekResult (non-destructive) so AwaitedSlot remains
            // queryable by callers via GetResult() after the callback runs.
        out << "                const auto& R = AwaitedSlot.PeekResult();\n";
        out << "                if (R.IsOk()) StoredValue = R.GetValue();\n";
        out << "            });\n";
        out << "        }\n";
        out << "        return Awaited;\n";
        out << "    }\n";
        out << "};\n";
        out << "\n";
    }

    // Emit a `struct Foo;` or `class Foo;` forward declaration for `TypeName`
    // if it's a plain identifier (not a template or pointer). Skip empty /
    // qualified / templated names to avoid malformed decls.
    static void EmitForwardDeclaration(std::ostringstream& out, const MString& TypeName)
    {
        if (TypeName.empty()) return;
        // Skip qualified names (Namespace::Type), templated names (Foo<Bar>),
        // and fundamental types (int, void, etc.).
        if (TypeName.find("::") != MString::npos) return;
        if (TypeName.find("<") != MString::npos) return;
        if (TypeName.find(">") != MString::npos) return;
        if (TypeName.find("(") != MString::npos) return;

        // Heuristic: `class` for type names starting with uppercase `M`,
        // `struct` otherwise. Doesn't matter for the actual definition
        // (linkage is the same), just affects compiler diagnostic clarity.
        const char* Keyword = (TypeName[0] == 'M') ? "class" : "struct";
        out << Keyword << " " << TypeName << ";\n";
    }

    // Emit `#include "<TypeName>.mgenerated.h"` so the Frame struct sees
    // a complete type. Used for generated protocol message types like
    // FSampleEchoResponse that are otherwise defined only in the user
    // header (which we can't include yet — the Frame must come first).
    static void EmitGeneratedTypeInclude(std::ostringstream& out, const MString& TypeName)
    {
        if (TypeName.empty()) return;
        if (TypeName.find("<") != MString::npos) return;
        if (TypeName.find("::") != MString::npos) return;
        out << "#include \"" << TypeName << ".mgenerated.h\"\n";
    }

    // =====================================================================
    // P5 — TAwaitable 单 await 状态机 Frame 生成（KD-12 最小形态）
    // =====================================================================
    //
    // 输入：函数（bIsAsync + AwaitSites 含 TAwaitableCall + LiveAcrossAwait）。
    // 输出：独立 `<Class>_P5AsyncFrames.h` 中的 Frame struct——
    //   Start()  触发第一个 await（调 F(args) → AsAwaiter）
    //   Resume() 挂起完成后恢复（awaiter 已 ready → AwaitResume 取值）
    //   GetFuture() 返回 SFutureResult<R>（Promise 驱动）
    // 本轮：单 await 形态（多 await 串行 / 循环 await 为 P5 后续工作包）。
    // 不替换 P4 生成器（KD-16 共存期 = 0 前，P5 产物独立输出）。

    // 从 `TAwaitable<F, R, Args...>(args...)` 提取 F / R / args 文本
    static bool ParseTAwaitableText(
        const MString& Text, MString& OutF, MString& OutR, MString& OutArgs)
    {
        const MString Prefix = "TAwaitable<";
        const size_t Start = Text.find(Prefix);
        if (Start == MString::npos) return false;
        const size_t Pos = Start + Prefix.size();
        // 模板参数列表可能含嵌套 <> 和括号（如 TAwaitable<int (*)(int), int, int>）——
        // 用 <> 深度匹配定位参数列表结束的 '>'，再取其后的 '('（调用括号）。
        int Depth = 1;
        size_t End = Pos;
        while (End < Text.size() && Depth > 0)
        {
            if (Text[End] == '<') ++Depth;
            else if (Text[End] == '>') --Depth;
            ++End;
        }
        if (End >= Text.size() || Text[End] != '(') return false;
        const size_t ArgsStart = End;
        MString TemplArgs = Text.substr(Pos, End - Pos - 1);
        std::vector<MString> Params;
        {
            int D = 0;
            size_t B = 0;
            for (size_t I = 0; I <= TemplArgs.size(); ++I)
            {
                if (I < TemplArgs.size())
                {
                    if (TemplArgs[I] == '<') ++D;
                    else if (TemplArgs[I] == '>') --D;
                }
                if (I == TemplArgs.size() || (D == 0 && TemplArgs[I] == ','))
                {
                    Params.push_back(MString(TemplArgs.substr(B, I - B)));
                    B = I + 1;
                }
            }
        }
        if (Params.size() < 2) return false;
        auto TrimP = [](MString In)
        {
            const size_t B = In.find_first_not_of(" \t\r\n");
            if (B == MString::npos) return MString();
            const size_t E = In.find_last_not_of(" \t\r\n");
            return In.substr(B, E - B + 1);
        };
        OutF = TrimP(Params[0]);
        OutR = TrimP(Params[1]);
        // 业务写 TAwaitable<decltype(&Func), R, Args...>（F 是函数指针类型）——
        // 生成器需要真实函数名才能生成 `Func(args)` 调用。提取 decltype(&X) 的 X。
        {
            const MString DTPrefix = "decltype(&";
            if (OutF.rfind(DTPrefix, 0) == 0 && OutF.back() == ')')
            {
                OutF = OutF.substr(DTPrefix.size(), OutF.size() - DTPrefix.size() - 1);
            }
        }
        size_t Close = ArgsStart + 1;
        int D2 = 1;
        while (Close < Text.size() && D2 > 0)
        {
            if (Text[Close] == '(') ++D2;
            else if (Text[Close] == ')') --D2;
            ++Close;
        }
        if (D2 != 0) return false;
        MString ArgsRaw = Text.substr(ArgsStart + 1, Close - ArgsStart - 2);
        {
            const size_t B = ArgsRaw.find_first_not_of(" \t\r\n");
            const size_t E = ArgsRaw.find_last_not_of(" \t\r\n");
            if (B != MString::npos) ArgsRaw = ArgsRaw.substr(B, E - B + 1);
        }
        OutArgs = ArgsRaw;
        return true;
    }

    // 解析循环 await 业务体（KD-13 最小形态：单 for + 体内单 await）：
    //   [循环前代码] for (init; cond; incr) { AccumVar += TAwaitable<...>(...); } [return <expr>;]
    // 提取：init/cond/incr、循环变量、累加语句前缀（AccumVar += ）、循环前代码、return 表达式。
    static bool ParseLoopAsyncBody(
        const MString& Body, const MString& AwaitText,
        MString& OutInit, MString& OutCond, MString& OutIncr, MString& OutLoopVar,
        MString& OutAccumPrefix, MString& OutPreCode, MString& OutPostReturnExpr,
        MString& OutInitValue)
    {
        const size_t ForPos = Body.find("for (");
        if (ForPos == MString::npos) return false;
        // 循环参数：init; cond; incr（括号内）
        const size_t OpenP = ForPos + 5;
        size_t CloseP = Body.find(')', OpenP);
        if (CloseP == MString::npos) return false;
        MString Head = Body.substr(OpenP, CloseP - OpenP);
        // 按顶层 ';' 分割（cond 里可能有 < 等，无 ; 干扰）
        size_t S1 = Head.find(';');
        size_t S2 = Head.find(';', S1 + 1);
        if (S1 == MString::npos || S2 == MString::npos) return false;
        OutInit = Head.substr(0, S1);
        OutCond = Head.substr(S1 + 1, S2 - S1 - 1);
        OutIncr = Head.substr(S2 + 1);
        // 循环变量（init 里 '=' 前最后一个标识符：int I = 0 → I）+ 初始值
        {
            const size_t Eq = OutInit.rfind('=');
            if (Eq != MString::npos)
            {
                // 变量名 = '=' 前最后一个 token
                const size_t EndV = OutInit.find_last_not_of(" \t", Eq - 1);
                const size_t StartV = OutInit.find_last_of(" \t", EndV);
                OutLoopVar = OutInit.substr(StartV == MString::npos ? 0 : StartV + 1,
                    EndV - (StartV == MString::npos ? 0 : StartV + 1) + 1);
                OutInitValue = OutInit.substr(Eq + 1);  // "0"
                // 保留类型+变量名（int I），去掉 '= 0'
                MString InitHead = OutInit.substr(0, Eq);
                const size_t E2 = InitHead.find_last_not_of(" \t");
                OutInit = InitHead.substr(0, E2 + 1);
            }
        }
        // 循环体：{ ... }
        const size_t BodyOpen = Body.find('{', CloseP);
        const size_t BodyClose = Body.find('}', BodyOpen);
        if (BodyOpen == MString::npos || BodyClose == MString::npos) return false;
        // 累加语句：await 表达式前的部分（如 "Sum += "）
        const size_t AwaitPos = Body.find(AwaitText, BodyOpen);
        if (AwaitPos == MString::npos || AwaitPos > BodyClose) return false;
        {
            // 行首到 await 表达式（含 "Sum += "）
            const size_t LineStart = Body.rfind('\n', AwaitPos) == MString::npos
                ? BodyOpen : Body.rfind('\n', AwaitPos) + 1;
            OutAccumPrefix = Body.substr(LineStart, AwaitPos - LineStart);
        }
        // 循环前代码（for 前，去 {）
        {
            MString Pre = Body.substr(0, ForPos);
            const size_t B = Pre.find_first_not_of(" \t\r\n{");
            const size_t E = Pre.find_last_not_of(" \t\r\n}");
            OutPreCode = (B == MString::npos) ? MString() : Pre.substr(B, E - B + 1);
        }
        // 循环后 return
        {
            const size_t RetPos = Body.find("return", BodyClose);
            if (RetPos != MString::npos)
            {
                const size_t Semi = Body.find(';', RetPos);
                if (Semi != MString::npos)
                {
                    MString Expr = Body.substr(RetPos + 6, Semi - RetPos - 6);
                    const size_t B = Expr.find_first_not_of(" \t\r\n");
                    const size_t E = Expr.find_last_not_of(" \t\r\n");
                    if (B != MString::npos) OutPostReturnExpr = Expr.substr(B, E - B + 1);
                }
            }
        }
        return true;
    }

    // 生成循环 await 状态机 Frame（KD-13 最小形态：单 for + 体内单 await）。
    // LoopEntry: cond 判断 → LoopBody(await) / LoopExit(return)
    // LoopBody 完成: 累加 → incr → LoopEntry
    MString EmitP5LoopAsyncFrame(
        const MString& NamePrefix,
        const fs::path& HeaderPath,
        const mession::headercodegen::SParsedFunction& Func,
        const mession::headercodegen::SAwaitSite* Site) const
    {
        (void)HeaderPath;
        MString F, R, Args;
        if (!ParseTAwaitableText(Site->AwaitExprText, F, R, Args)) return {};

        MString Init, InitValue, Cond, Incr, LoopVar, AccumPrefix, PreCode, PostReturnExpr;
        if (!ParseLoopAsyncBody(Func.AsyncBody, Site->AwaitExprText,
                Init, Cond, Incr, LoopVar, AccumPrefix, PreCode, PostReturnExpr, InitValue))
        {
            return {};
        }

        const MString FrameName =
            "MHeaderTool_P5Frame_" + SanitizeIdentifier(NamePrefix) +
            "_" + SanitizeIdentifier(Func.Name);

        std::ostringstream Out;
        Out << "// " << FrameName
            << ": P5 循环 await 状态机 Frame（KD-13 最小形态: 单 for + 单 await）\n";
        Out << "struct " << FrameName << "\n";
        Out << "{\n";
        for (const auto& P : Func.Params)
        {
            Out << "    " << P.Type.CanonicalName << " " << P.Name << "{};\n";
        }
        // 槽：LiveAcrossAwait + 循环变量
        for (const auto& L : Func.LiveAcrossAwait)
        {
            Out << "    " << L.Type.CanonicalName << " " << L.Name << "{};\n";
        }
        if (!LoopVar.empty())
        {
            bool bExist = false;
            for (const auto& L : Func.LiveAcrossAwait)
            {
                if (L.Name == LoopVar) { bExist = true; break; }
            }
            if (!bExist)
            {
                // 循环变量类型：从 init（"int I"）取类型部分
                MString VarType = Init;
                const size_t VS = VarType.find_last_of(" \t");
                if (VS != MString::npos) VarType = VarType.substr(0, VS);
                Out << "    " << VarType << " " << LoopVar << "{};\n";
            }
        }
        Out << "    TOptional<SFutureResult<" << R << ">::SAwaiter> Awaiter;\n";
        Out << "    MPromise<TResult<" << R << ", FAppError>> Promise;\n";
        Out << "    int State = 0;\n";
        Out << "\n";
        Out << "    void Start()\n";
        Out << "    {\n";
        if (!PreCode.empty())
        {
            Out << "        // 循环前业务代码（变量声明 → 槽赋值，去类型前缀）\n";
            MString Pre = PreCode;
            {
                // `int Sum = 0;` → `Sum = 0;`（变量 = 值，去类型声明——槽已建）
                const size_t Eq = Pre.find('=');
                if (Eq != MString::npos)
                {
                    const size_t EndV = Pre.find_last_not_of(" \t", Eq - 1);
                    if (EndV != MString::npos)
                    {
                        const size_t StartV = Pre.find_last_of(" \t", EndV);
                        MString Var = Pre.substr(StartV == MString::npos ? 0 : StartV + 1,
                            EndV - (StartV == MString::npos ? 0 : StartV + 1) + 1);
                        MString Val = Pre.substr(Eq + 1);
                        const size_t Semi = Val.find(';');
                        if (Semi != MString::npos) Val = Val.substr(0, Semi);
                        Pre = Var + " = " + Val + ";";
                    }
                }
            }
            Out << "        " << Pre << "\n";
        }
        if (!LoopVar.empty())
        {
            Out << "        " << LoopVar << " = " << InitValue << ";\n";
        }
        Out << "        LoopEntry();\n";
        Out << "    }\n";
        Out << "\n";
        Out << "    void LoopEntry()\n";
        Out << "    {\n";
        Out << "        if (" << Cond << ")\n";
        Out << "        {\n";
        Out << "            // LoopBody: await\n";
        Out << "            Awaiter = " << F << "(" << Args << ").AsAwaiter();\n";
        Out << "            if (Awaiter->AwaitReady())\n";
        Out << "            {\n";
        if (!AccumPrefix.empty())
        {
            Out << "                " << AccumPrefix << "Awaiter->AwaitResume();\n";
        }
        Out << "                LoopAdvance();\n";
        Out << "            }\n";
        Out << "            else\n";
        Out << "            {\n";
        Out << "                State = 1; Awaiter->AwaitSuspend(this);\n";
        Out << "            }\n";
        Out << "        }\n";
        Out << "        else\n";
        Out << "        {\n";
        Out << "            // LoopExit\n";
        Out << "            Finish();\n";
        Out << "        }\n";
        Out << "    }\n";
        Out << "\n";
        Out << "    void LoopAdvance()\n";
        Out << "    {\n";
        Out << "        " << Incr << ";\n";
        Out << "        LoopEntry();\n";
        Out << "    }\n";
        Out << "\n";
        Out << "    void Resume()\n";
        Out << "    {\n";
        Out << "        if (State == 1)\n";
        Out << "        {\n";
        if (!AccumPrefix.empty())
        {
            Out << "            " << AccumPrefix << "Awaiter->AwaitResume();\n";
        }
        Out << "            LoopAdvance();\n";
        Out << "        }\n";
        Out << "    }\n";
        Out << "\n";
        Out << "    void Finish()\n";
        Out << "    {\n";
        if (!PostReturnExpr.empty())
        {
            Out << "        Promise.SetValue(TResult<" << R
                << ", FAppError>::Ok(" << PostReturnExpr << "));\n";
        }
        else
        {
            Out << "        Promise.SetValue(TResult<" << R
                << ", FAppError>::Ok());\n";
        }
        Out << "    }\n";
        Out << "\n";
        Out << "    SFutureResult<" << R << "> GetFuture()\n";
        Out << "    {\n";
        Out << "        return SFutureResult<" << R << ">(Promise.GetFuture());\n";
        Out << "    }\n";
        Out << "};\n";
        return Out.str();
    }

    // 解析单 await 业务体（最小形态）：
    //   [await 前代码]  R = TAwaitable<F, R, Args...>(args);  [return <expr>;]
    // 提取：赋值变量名 R（空 = 无赋值）、await 前代码文本、await 后 return 表达式。
    static bool ParseSingleAwaitBody(
        const MString& Body, const MString& AwaitText,
        MString& OutAssignVar, MString& OutPreCode, MString& OutPostReturnExpr)
    {
        const size_t AwaitPos = Body.find(AwaitText);
        if (AwaitPos == MString::npos) return false;

        // 行首 → 赋值前缀（如 "        int R = "）
        const size_t LineStart = Body.rfind('\n', AwaitPos) == MString::npos
            ? 0 : Body.rfind('\n', AwaitPos) + 1;
        MString Prefix = Body.substr(LineStart, AwaitPos - LineStart);
        {
            // 赋值形态 `int R = TAwaitable<...>`——变量名在 '=' 前最后一个标识符。
            const size_t Eq = Prefix.rfind('=');
            if (Eq != MString::npos && Eq > 0)
            {
                const size_t End = Prefix.find_last_not_of(" \t", Eq - 1);
                if (End != MString::npos)
                {
                    const size_t Start = Prefix.find_last_of(" \t", End);
                    OutAssignVar = Prefix.substr(Start == MString::npos ? 0 : Start + 1,
                        End - (Start == MString::npos ? 0 : Start + 1) + 1);
                }
            }
            else
            {
                // 无赋值（裸 TAwaitable<...>(...) 语句）——变量名空
                OutAssignVar.clear();
            }
        }
        // await 前代码 = 之前的所有语句（LineStart 之前部分，去 {} 和首尾空白）
        OutPreCode = Body.substr(0, LineStart);

        // 语句结束 ';'
        const size_t StmtEnd = Body.find(';', AwaitPos + AwaitText.size());
        if (StmtEnd == MString::npos) return false;

        // await 后：'return <expr>;'（到 '}' 前）
        const size_t RetPos = Body.find("return", StmtEnd);
        if (RetPos != MString::npos)
        {
            const size_t Semi = Body.find(';', RetPos);
            if (Semi != MString::npos)
            {
                MString Expr = Body.substr(RetPos + 6, Semi - RetPos - 6);
                const size_t B = Expr.find_first_not_of(" \t\r\n");
                const size_t E = Expr.find_last_not_of(" \t\r\n");
                if (B != MString::npos)
                {
                    OutPostReturnExpr = Expr.substr(B, E - B + 1);
                }
            }
        }
        return true;
    }

    // 生成单个函数的 P5 Frame（单 await）。消费 IR 原生类型——AwaitSites /
    // LiveAcrossAwait 只在 IR 的 SParsedFunction 上（legacy shim 不携带）。
    // 生成单个函数的 P5 Frame（多 await 串行，KD-9/KD-12）。
    // 消费 IR 原生类型——AwaitSites/LiveAcrossAwait 只在 IR SParsedFunction 上。
    MString EmitP5AsyncFrame(
        const MString& NamePrefix,
        const fs::path& HeaderPath,
        const mession::headercodegen::SParsedFunction& Func) const
    {
        (void)HeaderPath;
        // 收集全部 TAwaitable 站点（按行排序 = 源码顺序）
        TVector<const mession::headercodegen::SAwaitSite*> Sites;
        for (const auto& S : Func.AwaitSites)
        {
            if (S.Kind == mession::headercodegen::EAwaitSiteKind::TAwaitableCall)
            {
                Sites.push_back(&S);
            }
        }
        if (Sites.empty()) return {};
        // 循环 await（KD-13）：AsyncBody 含 for 且首个 await 在循环体内 → 循环生成器
        if (Func.AsyncBody.find("for (") != MString::npos)
        {
            const MString LoopFrame = EmitP5LoopAsyncFrame(NamePrefix, HeaderPath, Func, Sites[0]);
            if (!LoopFrame.empty()) return LoopFrame;
            // 解析失败则回退串行路径
        }
        std::sort(Sites.begin(), Sites.end(),
            [](const mession::headercodegen::SAwaitSite* A,
               const mession::headercodegen::SAwaitSite* B)
            { return A->SourceLine < B->SourceLine; });

        const size_t N = Sites.size();
        TVector<MString> F(N), R(N), Args(N), AssignVar(N), SegCode(N);
        MString PostReturnExpr;

        for (size_t K = 0; K < N; ++K)
        {
            if (!ParseTAwaitableText(Sites[K]->AwaitExprText, F[K], R[K], Args[K]))
            {
                return {};
            }
            // 赋值变量：本 await 语句行首到 await 表达式（`int A = `）
            const size_t AwaitPos = Func.AsyncBody.find(Sites[K]->AwaitExprText);
            if (AwaitPos == MString::npos) return {};
            const size_t LineStart = Func.AsyncBody.rfind('\n', AwaitPos) == MString::npos
                ? 0 : Func.AsyncBody.rfind('\n', AwaitPos) + 1;
            MString Prefix = Func.AsyncBody.substr(LineStart, AwaitPos - LineStart);
            {
                const size_t Eq = Prefix.rfind('=');
                if (Eq != MString::npos && Eq > 0)
                {
                    const size_t EndV = Prefix.find_last_not_of(" \t", Eq - 1);
                    if (EndV != MString::npos)
                    {
                        const size_t StartV = Prefix.find_last_of(" \t", EndV);
                        AssignVar[K] = Prefix.substr(
                            StartV == MString::npos ? 0 : StartV + 1,
                            EndV - (StartV == MString::npos ? 0 : StartV + 1) + 1);
                    }
                }
            }
            // 本 await 语句结束 ';'
            const size_t StmtEnd = Func.AsyncBody.find(';', AwaitPos + Sites[K]->AwaitExprText.size());
            if (StmtEnd == MString::npos) return {};
            // 段 K（await K 语句后到 await K+1 行首）——await K+1 前业务代码
            if (K + 1 < N)
            {
                const size_t NextPos = Func.AsyncBody.find(Sites[K + 1]->AwaitExprText);
                if (NextPos != MString::npos)
                {
                    const size_t NextLine = Func.AsyncBody.rfind('\n', NextPos) == MString::npos
                        ? 0 : Func.AsyncBody.rfind('\n', NextPos) + 1;
                    // 段代码从下一行行首开始（跳过本行尾注释，如 `;  // await 1`）
                    const size_t SegStart = Func.AsyncBody.find('\n', StmtEnd);
                    MString Seg = (SegStart == MString::npos)
                        ? MString()
                        : Func.AsyncBody.substr(SegStart + 1, NextLine - SegStart - 1);
                    const size_t B = Seg.find_first_not_of(" \t\r\n");
                    const size_t E = Seg.find_last_not_of(" \t\r\n");
                    SegCode[K] = (B == MString::npos) ? MString() : Seg.substr(B, E - B + 1);
                }
            }
            else
            {
                // 最后一段：'return <expr>;'
                const size_t RetPos = Func.AsyncBody.find("return", StmtEnd);
                if (RetPos != MString::npos)
                {
                    const size_t Semi = Func.AsyncBody.find(';', RetPos);
                    if (Semi != MString::npos)
                    {
                        MString Expr = Func.AsyncBody.substr(RetPos + 6, Semi - RetPos - 6);
                        const size_t B = Expr.find_first_not_of(" \t\r\n");
                        const size_t E = Expr.find_last_not_of(" \t\r\n");
                        if (B != MString::npos) PostReturnExpr = Expr.substr(B, E - B + 1);
                    }
                }
            }
        }

        const MString FrameName =
            "MHeaderTool_P5Frame_" + SanitizeIdentifier(NamePrefix) +
            "_" + SanitizeIdentifier(Func.Name);

        // 生成"触发 await K"块（ready 路径内联展开后续 await；缩进统一 8 空格）。
        std::function<MString(size_t, const MString&)> GenAwait = [&](size_t K, const MString& Indent) -> MString
        {
            const MString AN = "Awaiter" + std::to_string(K + 1);
            MString Out;
            Out += Indent + AN + " = " + F[K] + "(" + Args[K] + ").AsAwaiter();  // 源码行 " +
                std::to_string(Sites[K]->SourceLine) + "\n";
            Out += Indent + "if (" + AN + "->AwaitReady())\n";
            Out += Indent + "{\n";
            if (!AssignVar[K].empty())
            {
                Out += Indent + "    " + AssignVar[K] + " = " + AN + "->AwaitResume();\n";
            }
            if (!SegCode[K].empty())
            {
                Out += Indent + "    // await " + std::to_string(K + 1) + " 完成后续业务代码\n";
                Out += Indent + "    " + SegCode[K] + "\n";
            }
            if (K + 1 < N)
            {
                Out += GenAwait(K + 1, Indent + "    ");
            }
            else
            {
                Out += Indent + "    Finish();\n";
            }
            Out += Indent + "}\n";
            Out += Indent + "else\n";
            Out += Indent + "{\n";
            Out += Indent + "    State = " + std::to_string(K + 1) +
                ";  // 等待 await " + std::to_string(K + 1) + " 完成（源码行 " +
                std::to_string(Sites[K]->SourceLine) + "）\n";
            Out += Indent + "    " + AN + "->AwaitSuspend(this);\n";
            Out += Indent + "}\n";
            return Out;
        };

        std::ostringstream Out;
        Out << "// " << FrameName << ": P5 状态机 Frame（await 串行, KD-9/KD-12）\n";
        Out << "struct " << FrameName << "\n";
        Out << "{\n";
        Out << "    // 函数参数\n";
        for (const auto& P : Func.Params)
        {
            Out << "    " << P.Type.CanonicalName << " " << P.Name << "{};\n";
        }
        bool bHasLive = false;
        for (const auto& L : Func.LiveAcrossAwait)
        {
            if (!bHasLive) { Out << "    // 跨 await 存活变量（Frame 持久化）\n"; bHasLive = true; }
            Out << "    " << L.Type.CanonicalName << " " << L.Name << "{};\n";
        }
        for (size_t K = 0; K < N; ++K)
        {
            if (AssignVar[K].empty()) continue;
            bool bExist = false;
            for (const auto& L : Func.LiveAcrossAwait)
            {
                if (L.Name == AssignVar[K]) { bExist = true; break; }
            }
            if (!bExist)
            {
                if (!bHasLive) { Out << "    // 跨 await 存活变量（Frame 持久化）\n"; bHasLive = true; }
                Out << "    " << R[K] << " " << AssignVar[K] << "{};\n";
            }
        }
        Out << "    // await 驱动\n";
        for (size_t K = 0; K < N; ++K)
        {
            Out << "    TOptional<SFutureResult<" << R[K] << ">::SAwaiter> Awaiter" << (K + 1) << ";\n";
        }
        Out << "    MPromise<TResult<" << R[0] << ", FAppError>> Promise;\n";
        Out << "    int State = 0;  // 0=初始, K=等待第 K 个 await 完成\n";
        Out << "\n";
        Out << "    void Start()\n";
        Out << "    {\n";
        {
            // 首个 await 前代码
            const size_t FirstPos = Func.AsyncBody.find(Sites[0]->AwaitExprText);
            const size_t FirstLine = Func.AsyncBody.rfind('\n', FirstPos) == MString::npos
                ? 0 : Func.AsyncBody.rfind('\n', FirstPos) + 1;
            MString Pre = Func.AsyncBody.substr(0, FirstLine);
            const size_t B = Pre.find_first_not_of(" \t\r\n{");
            const size_t E = Pre.find_last_not_of(" \t\r\n}");
            MString PreTrim = (B == MString::npos) ? MString() : Pre.substr(B, E - B + 1);
            if (!PreTrim.empty())
            {
                Out << "        // await 前业务代码\n";
                Out << "        " << PreTrim << "\n";
            }
        }
        Out << GenAwait(0, "        ");
        Out << "    }\n";
        Out << "\n";
        Out << "    void Resume()\n";
        Out << "    {\n";
        Out << "        switch (State)\n";
        Out << "        {\n";
        for (size_t K = 1; K <= N; ++K)
        {
            Out << "        case " << K << ":  // await " << K << " 完成（源码行 "
                << Sites[K - 1]->SourceLine << "）\n";
            if (!AssignVar[K - 1].empty())
            {
                Out << "            " << AssignVar[K - 1] << " = Awaiter" << K << "->AwaitResume();\n";
            }
            if (!SegCode[K - 1].empty() && K < N)
            {
                Out << "            // await " << K << " 后续业务代码\n";
                Out << "            " << SegCode[K - 1] << "\n";
            }
            if (K < N)
            {
                Out << GenAwait(K, "            ");
            }
            else
            {
                Out << "            Finish();\n";
            }
            Out << "            break;\n";
        }
        Out << "        default: break;\n";
        Out << "        }\n";
        Out << "    }\n";
        Out << "\n";
        Out << "    void Finish()\n";
        Out << "    {\n";
        if (!PostReturnExpr.empty())
        {
            Out << "        Promise.SetValue(TResult<" << R[0]
                << ", FAppError>::Ok(" << PostReturnExpr << "));\n";
        }
        else
        {
            Out << "        Promise.SetValue(TResult<" << R[0]
                << ", FAppError>::Ok());\n";
        }
        Out << "    }\n";
        Out << "\n";
        Out << "    SFutureResult<" << R[0] << "> GetFuture()\n";
        Out << "    {\n";
        Out << "        return SFutureResult<" << R[0] << ">(Promise.GetFuture());\n";
        Out << "    }\n";
        Out << "};\n";
        return Out.str();
    }

    // 生成 `<Class>_P5AsyncFrames.h`（含该 Record 所有 async 函数的 P5 Frame）
    MString EmitP5AsyncFramesHeader(
        const mession::headercodegen::SParsedRecord& Record) const
    {
        std::ostringstream Out;
        bool bAny = false;
        for (const auto& F : Record.Functions)
        {
            if (!F.bIsAsync) continue;
            const MString Frame = EmitP5AsyncFrame(Record.Name, Record.HeaderPath, F);
            if (!Frame.empty())
            {
                if (!bAny)
                {
                    Out << "#pragma once\n";
                    Out << "// Generated by MHeaderTool (P5 状态机, 单 await 形态)\n";
                    Out << "// Source: " << Record.HeaderPath.string() << "\n\n";
                    Out << "#include \"Common/Runtime/Async/MAsync.h\"\n";
                    Out << "#include \"Common/Runtime/Async/Awaitable.h\"\n";
                    Out << "#include \"Common/Runtime/Concurrency/Promise.h\"\n";
                    Out << "\n";
                    bAny = true;
                }
                Out << Frame << "\n";
            }
        }
        return bAny ? Out.str() : MString();
    }

    // 自由函数 P5 Frame（AsyncDemo2 形态）：按 HeaderPath 分组输出，
    // Frame 名前缀 Free（对齐 P4 EmitFreeAsyncStateMachine 命名）。
    MString EmitP5FreeAsyncFramesHeader(
        const TVector<mession::headercodegen::SParsedFunction>& FreeFuncs,
        const fs::path& HeaderPath) const
    {
        std::ostringstream Out;
        bool bAny = false;
        for (const auto& F : FreeFuncs)
        {
            if (!F.bIsAsync) continue;
            const MString Frame = EmitP5AsyncFrame("Free", HeaderPath, F);
            if (!Frame.empty())
            {
                if (!bAny)
                {
                    Out << "#pragma once\n";
                    Out << "// Generated by MHeaderTool (P5 状态机, 自由函数)\n";
                    Out << "// Source: " << HeaderPath.string() << "\n\n";
                    Out << "#include \"Common/Runtime/Async/MAsync.h\"\n";
                    Out << "#include \"Common/Runtime/Async/Awaitable.h\"\n";
                    Out << "#include \"Common/Runtime/Concurrency/Promise.h\"\n";
                    Out << "\n";
                    bAny = true;
                }
                Out << Frame << "\n";
            }
        }
        return bAny ? Out.str() : MString();
    }

