        MString MakeIncludePathFromHeader(const fs::path& headerPath) const {
            // 基于绝对路径中的 "/Source/" 段推导 include 路径，不依赖进程 cwd：
            // ClangTool 并行解析多个 TU 时会 chdir 到各 compile_commands 的
            // directory（Build/ 下，且线程间互相干扰），fs::current_path() 不可用。
            // /root/Mession/Source/Servers/... → Servers/...
            MString       P      = headerPath.generic_string();
            const MString Needle = "/Source/";
            const size_t  Pos    = P.find(Needle);
            if (Pos != MString::npos) {
                P = P.substr(Pos + Needle.size());
            } else {
                P = headerPath.filename().generic_string();
            }
            // codegen 专用源 `*.Async.cpp`：声明在同名业务头 `*.h`（去掉 .Async 后缀），
            // 不是 `*.Async.h`——否则 Impl include 到不存在的头。必须先于 `.cpp→.h` 转换。
            {
                const MString AsyncSuffix = ".Async.cpp";
                const size_t  Apos        = P.rfind(AsyncSuffix);
                if (Apos != MString::npos && Apos + AsyncSuffix.size() == P.size()) {
                    P = P.substr(0, Apos) + ".h";
                    return P;
                }
            }
            // 体在 .cpp（方案 B）时，生成实现 include 同名 .h（声明）而非 .cpp
            const MString Lower = P;
            if (Lower.size() > 4 && (Lower.substr(Lower.size() - 4) == ".cpp" || Lower.substr(Lower.size() - 4) == ".cc" || Lower.substr(Lower.size() - 3) == ".cxx")) {
                const size_t Dot = P.find_last_of('.');
                if (Dot != MString::npos)
                    P = P.substr(0, Dot) + ".h";
            }
            return P;
        }

