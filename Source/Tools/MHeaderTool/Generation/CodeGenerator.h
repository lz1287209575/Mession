        Out << "\n";
        Out << "    SFutureResult<" << R << "> GetFuture()\n";
        Out << "    {\n";
        Out << "        return SFutureResult<" << R << ">(Promise.GetFuture());\n";
        Out << "    }\n";
        Out << "};\n";
