    void GenerateServerCallHandler(std::ostringstream& out, const SParsedClass& parsedClass, const SParsedFunction& func) const
    {
        if (func.Params.empty()) return;

        MString handlerName = "MHeaderTool_HandleServerCall_" + SanitizeIdentifier(parsedClass.Name) + "_" + SanitizeIdentifier(func.Name);
        const auto& requestParam = func.Params[0];

        // Extract raw response type from `SFutureResult<FResp>` (CodeGenerator.h:766 ExtractResponseType).
        const MString responseType = ExtractResponseType(func.ReturnStorageType);

        out << "inline SFutureResult<TByteArray> " << handlerName << "(MObject* Object, const TByteArray& Payload)\n";
        out << "{\n";
        out << "    auto* TypedObject = static_cast<" << parsedClass.Name << "*>(Object);\n";
        out << "    if (!TypedObject)\n";
        out << "    {\n";
        out << "        return MServerCallAsyncSupport::MakeErrorFuture<TByteArray>(MString(\"server_call_invalid_object\"));\n";
        out << "    }\n";
        out << "    " << requestParam.StorageType << " RequestValue {};\n";
        out << "    auto ParseResult = ParsePayload(Payload, RequestValue, \"" << func.Name << "\");\n";
        out << "    if (!ParseResult.IsOk())\n";
        out << "    {\n";
        out << "        return MServerCallAsyncSupport::MakeErrorFuture<TByteArray>(ParseResult.GetError(), MString());\n";
        out << "    }\n";
        out << "    const SServerCallContext Context = CaptureCurrentServerCallContext();\n";
        out << "    (void)Context;\n";
        // P3 inline-body design: the user's Async body returns
        // `SF<RespType>` directly via `return AWAIT_OK(expr);`. The
        // generated Frame is just a helper struct that the body consumes.
        // Sync and Async ServerCall handlers therefore share the same
        // `TypedObject->Func(Request)` invocation + ready/pending bridge.
        out << "    SFutureResult<" << responseType << "> Inner = TypedObject->" << func.Name << "(std::move(RequestValue));\n";
        out << "    MPromise<TResult<TByteArray, FAppError>> OutPromise;\n";
        out << "    auto OutFuture = OutPromise.GetFuture();\n";
        out << "    if (Inner.IsReady())\n";
        out << "    {\n";
        out << "        TResult<" << responseType << ", FAppError> R = Inner.GetResult();\n";
        out << "        if (R.IsErr()) OutPromise.SetValue(TResult<TByteArray, FAppError>::Err(R.GetError()));\n";
        out << "        else OutPromise.SetValue(TResult<TByteArray, FAppError>::Ok(BuildPayload(R.GetValue())));\n";
        out << "        return SFutureResult<TByteArray>(OutFuture);\n";
        out << "    }\n";
        out << "    Inner.Then([OutPromise](MFuture<TResult<" << responseType << ", FAppError>> F) mutable\n";
        out << "    {\n";
        out << "        TResult<" << responseType << ", FAppError> R = F.Get();\n";
        out << "        if (R.IsErr()) OutPromise.SetValue(TResult<TByteArray, FAppError>::Err(R.GetError()));\n";
        out << "        else OutPromise.SetValue(TResult<TByteArray, FAppError>::Ok(BuildPayload(R.GetValue())));\n";
        out << "    });\n";
        out << "    return SFutureResult<TByteArray>(OutFuture);\n";
        out << "}\n";
        out << "\n";
    }

    void GenerateRpcWrapper(std::ostringstream& out, const SParsedClass& parsedClass, const SParsedFunction& func) const
    {
        out << "namespace MRpc\n";
        out << "{\n";
        out << "namespace " << SanitizeIdentifier(parsedClass.Name) << "\n";
        out << "{\n";
        out << "inline bool " << func.Name << "(TByteArray& OutData";
        for (const auto& param : func.Params)
        {
            out << ", " << param.Type << " " << param.Name;
        }
        out << ")\n";
        out << "{\n";
        out << "    return BuildRpcPayloadForRemoteCall(\"" << parsedClass.Name << "\", \"" << func.Name << "\", OutData";
        for (const auto& param : func.Params)
        {
            out << ", " << param.Name;
        }
        out << ");\n";
        out << "}\n";
        out << "template<typename TConnection>\n";
        out << "inline bool " << func.Name << "(TConnection&& Connection";
        for (const auto& param : func.Params)
        {
            out << ", " << param.Type << " " << param.Name;
        }
        out << ")\n";
        out << "{\n";
        out << "    TByteArray RpcPayload;\n";
        out << "    if (!" << func.Name << "(RpcPayload";
        for (const auto& param : func.Params)
        {
            out << ", " << param.Name;
        }
        out << ")) return false;\n";
        out << "    return SendServerRpcMessage(std::forward<TConnection>(Connection), RpcPayload);\n";
        out << "}\n";
        out << "} // namespace " << SanitizeIdentifier(parsedClass.Name) << "\n";
        out << "} // namespace MRpc\n";
        out << "\n";
    }

    void GenerateServerCallProxyImplementations(std::ostringstream& out, const SParsedClass& parsedClass) const
    {
        // 检查是否有 ServerCall 类型的函数
        bool hasServerCall = false;
        for (const auto& func : parsedClass.Functions)
        {
            if (func.Transport == "ServerCall")
            {
                hasServerCall = true;
                break;
            }
        }

        if (!hasServerCall)
        {
            return;
        }

        // 检查是否继承自 MServerCallProxyBase
        bool isProxyClass = false;
        for (const auto& parent : parsedClass.AllParentClasses)
        {
            if (parent == "MServerCallProxyBase")
            {
                isProxyClass = true;
                break;
            }
        }

        // 如果不是代理类，不生成 CallRemoteByName 实现
        if (!isProxyClass)
        {
            return;
        }

        // 生成 ServerCall 函数的实现
        for (const auto& func : parsedClass.Functions)
        {
            if (func.Transport != "ServerCall")
            {
                continue;
            }

            if (func.Params.empty())
            {
                continue;
            }

            // 获取请求参数（第一个参数是 Request）
            const auto& requestParam = func.Params[0];

            // 生成函数实现：调用 CallRemoteByName
            // TResponse 应该是原始响应类型（如 FPlayerEnterWorldResponse），CallRemoteByName 会内部包装到 TResult<>
            const MString responseType = ExtractResponseType(func.ReturnStorageType);
            out << func.ReturnStorageType << " " << parsedClass.Name << "::" << func.Name << "(" << requestParam.StorageType << " const& Request)\n";
            out << "{\n";
            out << "    return CallRemoteByName<" << responseType << ">(\"" << func.Name << "\", Request);\n";
            out << "}\n";
            out << "\n";
        }
    }

