        // 从 MFuture<TResult<T, E>> 中提取 T（原始响应类型）
        MString ExtractResponseType(const MString& returnType) const {
            // Strip SFutureResult<X> / MFuture<TResult<X, Y>> wrappers (and any
            // combination), returning the raw response type X. Used by the
            // generated ServerCall handler so it can call the typed method and
            // pattern-match on `TResult<RespType, FAppError>`.
            const MString sfPrefix = "SFutureResult<";
            const MString mfPrefix = "MFuture<TResult<";

            MString T = returnType;
            // Outer wrapper: SFutureResult<Inner>
            if (T.rfind(sfPrefix, 0) == 0 && T.back() == '>') {
                MString Inner = T.substr(sfPrefix.size(), T.size() - sfPrefix.size() - 1);
                return ExtractResponseType(Inner);
            }
            // Inner wrapper: MFuture<TResult<X, Y>>
            if (T.rfind(mfPrefix, 0) == 0 && T.back() == '>') {
                MString Inner = T.substr(mfPrefix.size(), T.size() - mfPrefix.size() - 1);
                size_t  comma = Inner.find(',');
                if (comma != MString::npos) {
                    return Inner.substr(0, comma);
                }
            }
            return T;
        }

        // P3 SPEC §6.3 HARD RULE: a non-Async function declared inside MCLASS may
        // NOT use AWAIT_OK. Emit a compile-time gate that the user will see at
        // build time. Async-without-AWAIT_OK is OK (handled by the existing
        // GenerateServerCallHandler pending branch — see line 731).
        void GenerateAwaitOkValidation(std::ostringstream& out, const SParsedClass& parsedClass, const SParsedFunction& func) const {
            if (func.bIsAsync)
                return;
            if (ScanAwaitOkSites(func.AsyncBody).empty())
                return;
            out << "// " << parsedClass.Name << "::" << func.Name << " — ERROR — non-Async function uses AWAIT_OK; spec 2026-07-24 §6.3.\n";
            out << "static_assert(true == false, \"P3: " << parsedClass.Name << "::" << func.Name << " uses AWAIT_OK but is not MFUNCTION(ServerCall, Async); see spec §6.3.\");\n";
        }

        // =========================================================================
        // P3: AWAIT_OK scanner + state machine generator
        // =========================================================================
        //
        // v1 scope (mirrors spec 2026-07-24 §7.3 subset):
        //   - Async functions may carry 0 or 1 AWAIT_OK statements at the top level.
        //     0 AWAIT_OKs is still allowed if the function's pending behavior comes
        //     from a ready SFutureResult<RespType>; that path is handled by the
        //     existing GenerateServerCallHandler pending branch.
        //   - 2+ AWAIT_OKs in a single Async function = static_assert error (P4 lifts).
        //   - Non-Async function with AWAIT_OK = static_assert error (spec §6.3).
        //   - AWAIT_OK(expr) where <expr> may contain arbitrary balanced ()s.
        // Each match becomes a single state slot in the generated Frame.
        // P3 v1 (spec §7.3 subset): ScanAwaitOkSites reports *how many* AWAIT_OK
        // sites appear at the top level of the user's inline body. Generator uses
        // only the count: 0 = no Frame, 1 = Frame helper, >=2 = static_assert.
        // (P4 lifts this to a multi-state Frame that slices body around sites.)
        struct SAwaitSite {
            size_t  ExprStart = 0; // byte offset of <expr> in AsyncBody
            size_t  ExprEnd   = 0; // byte offset just after <expr> (past ')')
            MString Expr;          // captured <expr> text (verbatim)
        };

        // Find AWAIT_OK statements (statement-level only). Walks past balanced
        // parens so that "AWAIT_OK(fn(a,b))" counts as one site, not three.
        TVector<SAwaitSite> ScanAwaitOkSites(const MString& Body) const {
            TVector<SAwaitSite> Sites;
            const MString       Needle    = "AWAIT_OK(";
            size_t              SearchPos = 0;
            while ((SearchPos = Body.find(Needle, SearchPos)) != MString::npos) {
                size_t ExprStart = SearchPos + Needle.size();
                int    Depth     = 1;
                size_t i         = ExprStart;
                while (i < Body.size() && Depth > 0) {
                    char ch = Body[i];
                    if (ch == '(')
                        ++Depth;
                    else if (ch == ')') {
                        if (Depth == 1)
                            break;
                        --Depth;
                    }
                    ++i;
                }
                if (Depth != 1 || i >= Body.size()) {
                    return {}; // malformed: caller will report
                }
                SAwaitSite Site;
                Site.ExprStart = ExprStart;
                Site.ExprEnd   = i;
                Site.Expr      = Body.substr(ExprStart, i - ExprStart);
                Sites.push_back(std::move(Site));
                SearchPos = i + 1;
            }
            return Sites;
        }

        // Emit the Frame struct + Run() entry for an Async function with a state
        // machine wrapping the user body. For zero-await Async functions this is a
        // no-op (no Frame is needed; SFutureResult pending already handled by
        // GenerateServerCallHandler pending branch).
        void GenerateAsyncStateMachine(std::ostringstream& out, const SParsedClass& parsedClass, const SParsedFunction& func) const {
            if (!func.bIsAsync)
                return;
            if (func.Params.empty())
                return;

            const MString FrameName = "MHeaderTool_AsyncFrame_" + SanitizeIdentifier(parsedClass.Name) + "_" + SanitizeIdentifier(func.Name);
            const MString ReqType   = func.Params[0].StorageType;
            const MString RespType  = ExtractResponseType(func.ReturnStorageType);

            TVector<SAwaitSite> AwaitSites = ScanAwaitOkSites(func.AsyncBody);
            if (AwaitSites.empty()) {
                // Zero-AWAIT_OK Async: function body has no `AWAIT_OK(...)` calls.
                // The Frame is unused in the user's body path; the existing
                // GenerateServerCallHandler ready/pending branch covers this case.
                // User's body — when eventually inline — would just `return MakeShared<...>`
                // of a ready SFutureResult, with no Frame interaction.
                out << "// " << FrameName << ": Async function with zero AWAIT_OK — no state machine emitted\n";
                out << "// (ServerCall handler bridges ready/pending SFutureResult already.)\n\n";
                return;
            }
            if (AwaitSites.size() > 1) {
                out << "// " << FrameName << ": ERROR — P3 v1 supports at most 1 AWAIT_OK per Async function,\n";
                out << "// this function has " << AwaitSites.size() << ". See spec 2026-07-24 §7.3.\n";
                out << "static_assert(true == false, \"P3 v1: Async function '" << func.Name << "' has " << AwaitSites.size() << " AWAIT_OK; max 1. See spec §7.3.\");\n\n";
                return;
            }

            // (P3 v1 supports exactly 1 AWAIT_OK site in inline body; sites[0] is
            //  referenced by no codegen path under the inline-body design — the
            //  user's body compiles verbatim, AwaitOk is the helper API.)

            // P3 v1 (spec 2026-07-24 §7.3): inline-body design. The user writes
            // the Async body inline in their header (a self-contained block that
            // constructs the Frame, sets Context/Service/Request, and uses the
            // AWAIT_OK macro to await one expression). The generator emits ONLY
            // the Frame helper struct; user body itself compiles normally and
            // drives dispatch. No `Run()` entry — the ServerCall handler just
            // calls TypedObject->Func(Request) and the user's body shapes the
            // SFutureResult path. No `Awaits=...` metadata — the await target
            // lives in the user's expression text, not in the macro.
            //
            // The Frame struct is emitted into a separate `<Class>_AsyncFrames.h`
            // file (see EmitAsyncFramesHeader). The user header must include that
            // file AFTER the headers defining ReqType/RespType/FAppError, so all
            // referenced types are already complete by the time the Frame struct
            // is parsed.

            // The Frame struct references ReqType / RespType / FAppError as
            // template arguments and members; its `SFutureResult<...>` member
            // forces `TOptional<TResult<T,E>>` (Promise state) to be
            // instantiated, which requires complete types at this point.
            //
            // For inline-body sites, the user header's own #include chain
            // transitively pulls in these types BEFORE the AsyncFrames header
            // is included. For direct consumers of AsyncFrames (unit tests,
            // other translation units), we emit explicit includes so the
            // header is self-contained. (The generated message headers do not
            // include the user header back, so this is safe — no circular
            // include.)
            EmitGeneratedTypeInclude(out, ReqType);
            EmitGeneratedTypeInclude(out, RespType);
            EmitGeneratedTypeInclude(out, "FAppError");

            // Forward-declare parsedClass.Name so the Frame can hold a pointer
            // to it (Service field). The class itself is defined later in the
            // user header, so we don't need its full definition here.
            EmitForwardDeclaration(out, parsedClass.Name);

            out << "// " << FrameName << ": Async frame helper (P3 v1, spec §7.3)\n";
            out << "//   User body constructs Frame, sets Service/Request/Ctx,\n";
            out << "//   returns AWAIT_OK(expr). AWAIT_OK -> Frame->AwaitOk(expr).\n";
            out << "//   AwaitOk is pass-through: returns Awaited verbatim so user\n";
            out << "//   body `return AWAIT_OK(expr)` matches the SF<Resp> signature.\n";
            out << "struct " << FrameName << "\n";
            out << "{\n";
            out << "    // Context (populated by user body)\n";
            out << "    MAsync::MAsyncContext* Ctx = nullptr;\n";
            out << "    " << parsedClass.Name << "* Service = nullptr;\n";
            out << "    " << ReqType << " Request;\n";
            out << "    // Single-await slot (P4 will split into per-state slots)\n";
            out << "    SFutureResult<" << RespType << "> AwaitedSlot;\n";
            out << "    " << RespType << " StoredValue {};\n";
            out << "\n";
            out << "    // AwaitOk — concrete-type entry used by the AWAIT_OK macro.\n";
            out << "//     Pass-through: returns Awaited so user body can write\n";
            out << "//     `return AWAIT_OK(expr);`. Records the awaitable in AwaitedSlot\n";
            out << "//     and snapshots the value into StoredValue (P4 state machine\n";
            out << "//     will read these; v1 just records).\n";
            out << "    SFutureResult<" << RespType << "> AwaitOk(SFutureResult<" << RespType << "> Awaited)\n";
            out << "    {\n";
            out << "        AwaitedSlot = Awaited;\n";
            out << "        if (Awaited.IsReady())\n";
            out << "        {\n";
            // Snapshot via IsOk/GetValue on the TResult reference, NOT via
            // MFuture::Get() which MOVES the value out of the shared state.
            // Awaited must remain valid for the caller's return path
            // (`return AWAIT_OK(expr);` passes Awaited back unchanged).
            out << "            const auto& R = Awaited.PeekResult();\n";
            out << "            if (R.IsOk()) StoredValue = R.GetValue();\n";
            out << "        }\n";
            out << "        else\n";
            out << "        {\n";
            out << "            Awaited.Then([this](MFuture<TResult<" << RespType << ", FAppError>> /*F*/)\n";
            out << "            {\n";
            out << "                if (!AwaitedSlot.IsReady()) return;\n";
            // Use PeekResult (non-destructive) so AwaitedSlot remains
            // queryable by callers via GetResult() after the callback runs.
            out << "                const auto& R = AwaitedSlot.PeekResult();\n";
            out << "                if (R.IsOk()) StoredValue = R.GetValue();\n";
            out << "            });\n";
            out << "        }\n";
            out << "        return Awaited;\n";
            out << "    }\n";
            out << "};\n";
            out << "\n";
        }

        // Emit a `struct Foo;` or `class Foo;` forward declaration for `TypeName`
        // if it's a plain identifier (not a template or pointer). Skip empty /
        // qualified / templated names to avoid malformed decls.
        static void EmitForwardDeclaration(std::ostringstream& out, const MString& TypeName) {
            if (TypeName.empty())
                return;
            // Skip qualified names (Namespace::Type), templated names (Foo<Bar>),
            // and fundamental types (int, void, etc.).
            if (TypeName.find("::") != MString::npos)
                return;
            if (TypeName.find("<") != MString::npos)
                return;
            if (TypeName.find(">") != MString::npos)
                return;
            if (TypeName.find("(") != MString::npos)
                return;

            // Heuristic: `class` for type names starting with uppercase `M`,
            // `struct` otherwise. Doesn't matter for the actual definition
            // (linkage is the same), just affects compiler diagnostic clarity.
            const char* Keyword = (TypeName[0] == 'M') ? "class" : "struct";
            out << Keyword << " " << TypeName << ";\n";
        }

        // Emit `#include "<TypeName>.mgenerated.h"` so the Frame struct sees
        // a complete type. Used for generated protocol message types like
        // FSampleEchoResponse that are otherwise defined only in the user
        // header (which we can't include yet — the Frame must come first).
        static void EmitGeneratedTypeInclude(std::ostringstream& out, const MString& TypeName) {
            if (TypeName.empty())
                return;
            if (TypeName.find("<") != MString::npos)
                return;
            if (TypeName.find("::") != MString::npos)
                return;
            out << "#include \"" << TypeName << ".mgenerated.h\"\n";
        }

        // =====================================================================
        // P5 — TAwaitable 单 await 状态机 Frame 生成（KD-12 最小形态）
        // =====================================================================
        //
        // 输入：函数（bIsAsync + AwaitSites 含 TAwaitableCall + LiveAcrossAwait）。
        // 输出：独立 `<Class>_AwaitStateMachine.h` 中的 Frame struct——
        //   Start()  触发第一个 await（调 F(args) → AsAwaiter）
        //   Resume() 挂起完成后恢复（awaiter 已 ready → AwaitResume 取值）
        //   GetFuture() 返回 SFutureResult<R>（Promise 驱动）
        // 控制流：单 await / 多 await 串行 / if-else 分支 / for 循环 / 嵌套均以实现
        //（简单串行走本函数；含 if/for 的走 EmitAwaitCFrame 递归控制流；
        //  验证见 AwaitCodegenTest 32 用例）。不替换 P4 生成器（KD-16 共存期
        //  = 0 前，P5 产物独立输出）。

        // 参数槽类型：去 const 前缀 + 尾随 &/*（成员不能是引用/const 值）
        static MString StripParamQualifiers(MString TypeName) {
            while (TypeName.rfind("const ", 0) == 0) {
                TypeName       = TypeName.substr(6);
                const size_t B = TypeName.find_first_not_of(" \t");
                TypeName       = (B == MString::npos) ? MString() : TypeName.substr(B);
            }
            while (!TypeName.empty() && (TypeName.back() == '&' || TypeName.back() == '*')) {
                TypeName.pop_back();
                const size_t E = TypeName.find_last_not_of(" \t");
                TypeName       = (E == MString::npos) ? MString() : TypeName.substr(0, E + 1);
            }
            return TypeName;
        }

        // 从 `TAwaitable<F, R, Args...>(args...)` 提取 F / R / args 文本
        // 最简签名：R 从函数返回类型（SFutureResult<R>）剥出
        static MString RFromReturnType(const MString& CanonicalReturnType) {
            MString       R = CanonicalReturnType;
            const MString P = "SFutureResult<";
            if (R.rfind(P, 0) == 0 && R.size() > P.size() && R.back() == '>') {
                R = R.substr(P.size(), R.size() - P.size() - 1);
            }
            return R;
        }

        static bool ParseTAwaitableText(const MString& Text, MString& OutF, MString& OutR, MString& OutArgs, bool& OutMember, MString& OutObj) {
            const MString Prefix = "TAwaitable<";
            const size_t  Start  = Text.find(Prefix);
            if (Start == MString::npos)
                return false;
            const size_t Pos = Start + Prefix.size();
            // 模板参数列表可能含嵌套 <> 和括号（如 TAwaitable<int (*)(int), int, int>）——
            // 用 <> 深度匹配定位参数列表结束的 '>'，再取其后的 '('（调用括号）。
            int    Depth = 1;
            size_t End   = Pos;
            while (End < Text.size() && Depth > 0) {
                if (Text[End] == '<')
                    ++Depth;
                else if (Text[End] == '>')
                    --Depth;
                ++End;
            }
            if (End >= Text.size() || Text[End] != '(')
                return false;
            const size_t         ArgsStart = End;
            MString              TemplArgs = Text.substr(Pos, End - Pos - 1);
            std::vector<MString> Params;
            {
                int    D = 0;
                size_t B = 0;
                for (size_t I = 0; I <= TemplArgs.size(); ++I) {
                    if (I < TemplArgs.size()) {
                        if (TemplArgs[I] == '<')
                            ++D;
                        else if (TemplArgs[I] == '>')
                            --D;
                    }
                    if (I == TemplArgs.size() || (D == 0 && TemplArgs[I] == ',')) {
                        Params.push_back(MString(TemplArgs.substr(B, I - B)));
                        B = I + 1;
                    }
                }
            }
            if (Params.empty())
                return false;
            auto TrimP = [](MString In) {
                const size_t B = In.find_first_not_of(" \t\r\n");
                if (B == MString::npos)
                    return MString();
                const size_t E = In.find_last_not_of(" \t\r\n");
                return In.substr(B, E - B + 1);
            };
            OutF = TrimP(Params[0]);
            // 最简签名 TAwaitable<F>(args)：R 不写，由调用处从函数返回类型补；
            // 兼容旧写法 TAwaitable<F, R, Args...>(args)（R = Params[1]）。
            OutR = (Params.size() >= 2) ? TrimP(Params[1]) : MString();
            // 兼容旧写法 TAwaitable<decltype(&Func), R, Args...>（F 是函数指针类型）——
            // 生成器需要真实函数名才能生成调用。提取 decltype(&X) 的 X 并保留 '&'（成员
            // 函数指针 &C::M 需要 &；自由函数 &Func 的 & 在后面统一剥掉）。
            {
                const MString DTPrefix = "decltype(";
                if (OutF.rfind(DTPrefix, 0) == 0 && OutF.back() == ')') {
                    OutF = OutF.substr(DTPrefix.size(), OutF.size() - DTPrefix.size() - 1);
                }
            }
            size_t Close = ArgsStart + 1;
            int    D2    = 1;
            while (Close < Text.size() && D2 > 0) {
                if (Text[Close] == '(')
                    ++D2;
                else if (Text[Close] == ')')
                    --D2;
                ++Close;
            }
            if (D2 != 0)
                return false;
            MString ArgsRaw = Text.substr(ArgsStart + 1, Close - ArgsStart - 2);
            {
                const size_t B = ArgsRaw.find_first_not_of(" \t\r\n");
                const size_t E = ArgsRaw.find_last_not_of(" \t\r\n");
                if (B != MString::npos)
                    ArgsRaw = ArgsRaw.substr(B, E - B + 1);
            }
            OutArgs = ArgsRaw;

            // 成员函数指针 `&C::M`：分离对象参数（Args 第一个）与成员调用参数（其余）。
            // 生成侧统一 std::invoke(&C::M, obj, args...)——对象可为值/指针/引用。
            OutMember = false;
            OutObj.clear();
            if (!OutF.empty() && OutF[0] == '&') {
                if (OutF.find("::") != MString::npos) {
                    OutMember    = true;
                    int    D     = 0;
                    size_t Comma = MString::npos;
                    for (size_t I = 0; I < OutArgs.size(); ++I) {
                        const char C = OutArgs[I];
                        if (C == '(' || C == '<' || C == '[') {
                            ++D;
                        } else if (C == ')' || C == '>' || C == ']') {
                            --D;
                        } else if (C == ',' && D == 0) {
                            Comma = I;
                            break;
                        }
                    }
                    if (Comma == MString::npos) {
                        OutObj = TrimP(OutArgs);
                        OutArgs.clear();
                    } else {
                        OutObj         = TrimP(OutArgs.substr(0, Comma));
                        const size_t B = OutArgs.find_first_not_of(" \t", Comma + 1);
                        OutArgs        = (B == MString::npos) ? MString() : OutArgs.substr(B);
                    }
                } else {
                    OutF = OutF.substr(1); // &Func → Func（自由函数）
                }
            }
            return true;
        }

        // 生成 await 目标调用表达式：自由函数 `F(args)`；成员函数指针 `&C::M`
        // 用 std::invoke(&C::M, obj, args...)——对象可为值/指针/引用/this，
        // 无需区分对象形态（`.Member()` 与 `->Member()` 的差异由 invoke 处理）。
        static MString MakeAwaitCall(const MString& F, const MString& Obj, const MString& Args, bool bMember) {
            if (!bMember) {
                return F + "(" + Args + ")";
            }
            MString Call = "std::invoke(" + F + ", " + Obj;
            if (!Args.empty()) {
                Call += ", " + Args;
            }
            Call += ")";
            return Call;
        }

        // 解析循环 await 业务体（KD-13 最小形态：单 for + 体内单 await）：
        //   [循环前代码] for (init; cond; incr) { AccumVar += TAwaitable<...>(...); } [return <expr>;]
        // 提取：init/cond/incr、循环变量、累加语句前缀（AccumVar += ）、循环前代码、return 表达式。
        // 控制流节点：AsyncBody → 树（Seq/If/For/Return/Await/Raw），递归生成状态机。
        struct CFlowNode {
            enum class EKind : uint8_t { Seq, If, For, Return, Await, Raw };
            EKind              Kind = EKind::Raw;
            MString            Text;                              // Raw: 语句; If: cond; For: "init;cond;incr"; Return: expr; Await: 调用参数
            MString            AssignVar;                         // Await: 赋值变量（空 = 无赋值/累加）
            MString            F, R, Args;                        // Await: 目标解析
            MString            Obj;                               // Await: 成员函数目标的对象（bMember）
            bool               bMember = false;                   // Await: 目标是成员函数指针 &C::M
            MString            LInit, LCond, LIncr, LAccumPrefix; // For: 循环参数
            TVector<CFlowNode> Children;                          // Seq: 语句; If: [then(0), else(1)（可空）]; For: [body]
            size_t             AwaitIndex     = 0;                // Await 全局编号
            size_t             LoopIndex      = 0;                // For 循环编号（方法命名 LoopEntry_N）
            bool               bHasElse       = false;
            bool               bIsReturnAwait = false; // return TAwaitable<...>：作为最后 await 展开
        };

        // 剥离注释（// 行注释、/* */ 块注释）——替换为空格（保留 '\n' 行结构）。
        // 避免注释文本里的 return/if (/TAwaitable< 干扰控制流解析。
        static MString StripComments(const MString& In) {
            MString Out = In;
            size_t  i   = 0;
            while (i < Out.size()) {
                // 字符串/字符字面量：跳过（避免剥掉 "http://..." 等文本里的注释标记）
                if (Out[i] == '"' || Out[i] == '\'') {
                    const char Quote = Out[i];
                    ++i;
                    while (i < Out.size()) {
                        if (Out[i] == '\\' && i + 1 < Out.size())
                            i += 2;
                        else if (Out[i] == Quote) {
                            ++i;
                            break;
                        } else
                            ++i;
                    }
                    continue;
                }
                if (Out[i] == '/' && i + 1 < Out.size() && Out[i + 1] == '/') {
                    Out[i]     = ' ';
                    Out[i + 1] = ' ';
                    i += 2;
                    while (i < Out.size() && Out[i] != '\n') {
                        Out[i] = ' ';
                        ++i;
                    }
                } else if (Out[i] == '/' && i + 1 < Out.size() && Out[i + 1] == '*') {
                    Out[i]     = ' ';
                    Out[i + 1] = ' ';
                    i += 2;
                    while (i + 1 < Out.size() && !(Out[i] == '*' && Out[i + 1] == '/')) {
                        if (Out[i] != '\n')
                            Out[i] = ' ';
                        ++i;
                    }
                    if (i + 1 < Out.size()) {
                        Out[i]     = ' ';
                        Out[i + 1] = ' ';
                        i += 2;
                    }
                } else {
                    ++i;
                }
            }
            return Out;
        }

        // 递归下降解析：Code（一段函数体，无外层大括号）→ 控制流节点列表。
        // Sites 按源码顺序消费（InOutSiteIndex 递增）；OutEndPos = 消费到的位置
        // （Code.size() = 末尾，否则 '}' 之后）。
        static bool ParseControlFlow(const MString& Code, const TVector<mession::headercodegen::SAwaitSite>& Sites, size_t& InOutSiteIndex, TVector<CFlowNode>& OutNodes, size_t& OutEndPos) {
            size_t Pos = 0;
            while (Pos < Code.size()) {
                const size_t B = Code.find_first_not_of(" \t\r\n", Pos);
                if (B == MString::npos) {
                    OutEndPos = Code.size();
                    return true;
                }
                if (Code[B] == '}') {
                    OutEndPos = B + 1;
                    return true;
                }
                // ---- if (cond) { ... } [else ...] ----
                if (Code.compare(B, 4, "if (") == 0) {
                    const size_t CondOpen = B + 3;
                    int          CDepth   = 1;
                    size_t       CondEnd  = CondOpen + 1;
                    while (CondEnd < Code.size() && CDepth > 0) {
                        if (Code[CondEnd] == '(')
                            ++CDepth;
                        else if (Code[CondEnd] == ')')
                            --CDepth;
                        ++CondEnd;
                    }
                    if (CDepth != 0)
                        return false;
                    CFlowNode IfNode;
                    IfNode.Kind            = CFlowNode::EKind::If;
                    IfNode.Text            = TrimText(Code.substr(CondOpen + 1, CondEnd - CondOpen - 2));
                    const size_t BraceOpen = Code.find('{', CondEnd);
                    if (BraceOpen == MString::npos)
                        return false;
                    int    BD       = 1;
                    size_t BraceEnd = BraceOpen + 1;
                    while (BraceEnd < Code.size() && BD > 0) {
                        if (Code[BraceEnd] == '{')
                            ++BD;
                        else if (Code[BraceEnd] == '}')
                            --BD;
                        ++BraceEnd;
                    }
                    if (BD != 0)
                        return false;
                    const MString ThenCode = Code.substr(BraceOpen + 1, BraceEnd - BraceOpen - 2);
                    CFlowNode     ThenSeq;
                    ThenSeq.Kind = CFlowNode::EKind::Seq;
                    size_t ThenEnd;
                    if (!ParseControlFlow(ThenCode, Sites, InOutSiteIndex, ThenSeq.Children, ThenEnd))
                        return false;
                    IfNode.Children.push_back(ThenSeq);
                    // else / else-if 链
                    size_t AfterIf = BraceEnd;
                    {
                        const size_t EB = Code.find_first_not_of(" \t\r\n", AfterIf);
                        if (EB != MString::npos && Code.compare(EB, 4, "else") == 0 && (EB + 4 >= Code.size() || Code[EB + 4] == '{' || Code[EB + 4] == ' ' || Code[EB + 4] == '\t' || Code[EB + 4] == '\n' || Code[EB + 4] == 'i')) {
                            IfNode.bHasElse = true;
                            CFlowNode ElseSeq;
                            ElseSeq.Kind = CFlowNode::EKind::Seq;
                            // else-if 链：`else if (c2) {...} [else {...}]`——把 `if (c2)...`
                            // 当作独立 If 节点递归解析（条件保留）
                            const size_t ElseIfP = (Code.compare(EB + 4, 3, " if") == 0 || (EB + 7 < Code.size() && Code[EB + 4] == ' ' && Code[EB + 5] == 'i' && Code[EB + 6] == 'f')) ? EB + 4 : MString::npos;
                            if (ElseIfP != MString::npos) {
                                // 从 else-if 的 `if` 位置递归解析一个 If 节点
                                TVector<CFlowNode> NestedIf;
                                size_t             NestedEnd = 0;
                                const size_t       IfB       = Code.find("if (", ElseIfP);
                                if (IfB != MString::npos) {
                                    if (!ParseControlFlow(Code.substr(IfB), Sites, InOutSiteIndex, NestedIf, NestedEnd))
                                        return false;
                                    ElseSeq.Children = NestedIf;
                                    AfterIf          = IfB + NestedEnd;
                                } else {
                                    return false;
                                }
                            } else {
                                const size_t ElseOpen = Code.find('{', EB);
                                if (ElseOpen == MString::npos)
                                    return false;
                                int    EBD     = 1;
                                size_t ElseEnd = ElseOpen + 1;
                                while (ElseEnd < Code.size() && EBD > 0) {
                                    if (Code[ElseEnd] == '{')
                                        ++EBD;
                                    else if (Code[ElseEnd] == '}')
                                        --EBD;
                                    ++ElseEnd;
                                }
                                if (EBD != 0)
                                    return false;
                                const MString ElseCode = Code.substr(ElseOpen + 1, ElseEnd - ElseOpen - 2);
                                size_t        ElseEndPos;
                                if (!ParseControlFlow(ElseCode, Sites, InOutSiteIndex, ElseSeq.Children, ElseEndPos))
                                    return false;
                                AfterIf = ElseEnd;
                            }
                            IfNode.Children.push_back(ElseSeq);
                        }
                    }
                    OutNodes.push_back(IfNode);
                    Pos = AfterIf;
                    continue;
                }

                // ---- for (init; cond; incr) { body } ----
                if (Code.compare(B, 5, "for (") == 0) {
                    const size_t ForOpen  = B + 4;
                    size_t       ForClose = Code.find(')', ForOpen);
                    if (ForClose == MString::npos)
                        return false;
                    CFlowNode ForNode;
                    ForNode.Kind = CFlowNode::EKind::For;
                    ForNode.Text = TrimText(Code.substr(ForOpen + 1, ForClose - ForOpen - 1));
                    // 拆 init; cond; incr
                    const size_t S1 = ForNode.Text.find(';');
                    const size_t S2 = ForNode.Text.find(';', S1 + 1);
                    if (S1 == MString::npos || S2 == MString::npos)
                        return false;
                    ForNode.LInit          = TrimText(ForNode.Text.substr(0, S1));
                    ForNode.LCond          = TrimText(ForNode.Text.substr(S1 + 1, S2 - S1 - 1));
                    ForNode.LIncr          = TrimText(ForNode.Text.substr(S2 + 1));
                    const size_t BraceOpen = Code.find('{', ForClose);
                    if (BraceOpen == MString::npos)
                        return false;
                    int    BD       = 1;
                    size_t BraceEnd = BraceOpen + 1;
                    while (BraceEnd < Code.size() && BD > 0) {
                        if (Code[BraceEnd] == '{')
                            ++BD;
                        else if (Code[BraceEnd] == '}')
                            --BD;
                        ++BraceEnd;
                    }
                    if (BD != 0)
                        return false;
                    const MString BodyCode = Code.substr(BraceOpen + 1, BraceEnd - BraceOpen - 2);
                    CFlowNode     BodySeq;
                    BodySeq.Kind = CFlowNode::EKind::Seq;
                    size_t BodyEnd;
                    if (!ParseControlFlow(BodyCode, Sites, InOutSiteIndex, BodySeq.Children, BodyEnd))
                        return false;
                    ForNode.Children.push_back(BodySeq);
                    OutNodes.push_back(ForNode);
                    Pos = BraceEnd;
                    continue;
                }

                // ---- return <expr>; ----
                if (Code.compare(B, 6, "return") == 0 && (B + 6 >= Code.size() || isspace(static_cast<unsigned char>(Code[B + 6])))) {
                    const size_t Semi = Code.find(';', B);
                    if (Semi == MString::npos)
                        return false;
                    const MString RetExpr = TrimText(Code.substr(B + 6, Semi - B - 6));
                    // return await：`return TAwaitable<F>(args)` 作为最后 await 展开
                    //（语义 = await 目标结果直接作为函数返回值，与普通 return 区分）。
                    if (RetExpr.find("TAwaitable<") != MString::npos) {
                        if (InOutSiteIndex >= Sites.size())
                            return false;
                        const mession::headercodegen::SAwaitSite* AS = &Sites[InOutSiteIndex];
                        CFlowNode                                 Aw;
                        Aw.Kind       = CFlowNode::EKind::Await;
                        Aw.Text       = AS->AwaitExprText;
                        Aw.AwaitIndex = InOutSiteIndex;
                        if (!ParseTAwaitableText(AS->AwaitExprText, Aw.F, Aw.R, Aw.Args, Aw.bMember, Aw.Obj))
                            return false;
                        Aw.bIsReturnAwait = true;
                        ++InOutSiteIndex;
                        OutNodes.push_back(Aw);
                        Pos = Semi + 1;
                        continue;
                    }
                    CFlowNode Ret;
                    Ret.Kind = CFlowNode::EKind::Return;
                    Ret.Text = RetExpr;
                    OutNodes.push_back(Ret);
                    Pos = Semi + 1;
                    continue;
                }

                // ---- TAwaitable<...>(...)（await 语句）----
                if (Code.compare(B, 11, "TAwaitable<") == 0) {
                    if (InOutSiteIndex >= Sites.size()) {
                        return false;
                    }
                    const mession::headercodegen::SAwaitSite* AS = &Sites[InOutSiteIndex];
                    CFlowNode                                 Aw;
                    Aw.Kind       = CFlowNode::EKind::Await;
                    Aw.Text       = AS->AwaitExprText;
                    Aw.AwaitIndex = InOutSiteIndex;
                    if (!ParseTAwaitableText(AS->AwaitExprText, Aw.F, Aw.R, Aw.Args, Aw.bMember, Aw.Obj))
                        return false;
                    // 赋值变量（行首 '=' 前；复合赋值 → 空）
                    {
                        const size_t  LineStart = Code.rfind('\n', B) == MString::npos ? 0 : Code.rfind('\n', B) + 1;
                        const MString Line      = Code.substr(LineStart, B - LineStart);
                        const size_t  Eq        = Line.rfind('=');
                        if (Eq != MString::npos && (Eq == 0 || (Line[Eq - 1] != '+' && Line[Eq - 1] != '-' && Line[Eq - 1] != '*' && Line[Eq - 1] != '/'))) {
                            const size_t EndV = Line.find_last_not_of(" \t", Eq - 1);
                            if (EndV != MString::npos) {
                                const size_t StartV = Line.find_last_of(" \t", EndV);
                                Aw.AssignVar        = Line.substr(StartV == MString::npos ? 0 : StartV + 1, EndV - (StartV == MString::npos ? 0 : StartV + 1) + 1);
                            }
                        }
                        // 累加前缀（`Sum += `）
                        const size_t AEq = Line.rfind('=');
                        if (AEq != MString::npos && AEq > 0 && (Line[AEq - 1] == '+' || Line[AEq - 1] == '-' || Line[AEq - 1] == '*' || Line[AEq - 1] == '/')) {
                            const size_t EndV = Line.find_last_not_of(" \t", AEq - 2);
                            if (EndV != MString::npos) {
                                const size_t  StartV = Line.find_last_of(" \t", EndV);
                                const MString LV     = Line.substr(StartV == MString::npos ? 0 : StartV + 1, EndV - (StartV == MString::npos ? 0 : StartV + 1) + 1);
                                MString       Op     = Line.substr(AEq - 1, 1);
                                Aw.LAccumPrefix      = LV + Op + "= ";
                            }
                        }
                    }
                    ++InOutSiteIndex;
                    // 跳过语句其余（到 ';'）
                    const size_t Semi = Code.find(';', B);
                    Pos               = (Semi == MString::npos) ? Code.size() : Semi + 1;
                    OutNodes.push_back(Aw);
                    continue;
                }

                // ---- Raw 语句（到 ';' 或 '}' / 结构标记）----
                {
                    size_t Semi = Code.find(';', B);
                    // 若 ';' 前有结构标记（if/for/return/TAwaitable）——截断
                    const size_t NextIf  = Code.find("if (", B);
                    const size_t NextFor = Code.find("for (", B);
                    const size_t NextRet = Code.find("return", B);
                    const size_t NextAw  = Code.find("TAwaitable<", B);
                    size_t       Cut     = Semi;
                    if (NextIf != MString::npos && NextIf < Cut)
                        Cut = NextIf;
                    if (NextFor != MString::npos && NextFor < Cut)
                        Cut = NextFor;
                    if (NextRet != MString::npos && NextRet < Cut)
                        Cut = NextRet;
                    if (NextAw != MString::npos && NextAw < Cut)
                        Cut = NextAw;
                    if (Cut == MString::npos || Cut <= B) {
                        return false;
                    }
                    CFlowNode Raw;
                    Raw.Kind = CFlowNode::EKind::Raw;
                    Raw.Text = TrimText(Code.substr(B, Cut - B));
                    OutNodes.push_back(Raw);
                    // 若 Cut 是 ';'（完整语句）跳过；若是结构标记（截断的赋值前缀）停在标记处
                    Pos = (Semi != MString::npos && Cut == Semi) ? Semi + 1 : Cut;
                    continue;
                }
            }
            OutEndPos = Code.size();
            return true;
        }

        static MString TrimText(const MString& In) {
            const size_t B = In.find_first_not_of(" \t\r\n");
            if (B == MString::npos)
                return MString();
            const size_t E = In.find_last_not_of(" \t\r\n");
            return In.substr(B, E - B + 1);
        }


        // 业务函数体 return 写完整表达式（`SFutureResult<T>(TResult<T,E>::Ok(x))`）
        // 以保证 #ifdef 体在 C++ 下可编译；生成器剥到裸值再包 Ok（与裸值 return
        // 契约一致，兼容两种写法）。只剥构造包裹（SFutureResult/Ok/TResult），
        // 普通表达式（`R + 1`、`(A+B)*2`）原样返回。
        static MString StripValueWrapper(const MString& Expr) {
            MString V         = Expr;
            bool    bStripped = true;
            while (bStripped) {
                bStripped         = false;
                const size_t Open = V.find('(');
                if (Open == MString::npos || Open == 0)
                    break;
                const MString Prefix = V.substr(0, Open);
                if (Prefix.find("SFutureResult") == MString::npos && Prefix.find("Ok") == MString::npos && Prefix.find("TResult") == MString::npos) {
                    break;
                }
                int    Depth = 1;
                size_t I     = Open + 1;
                for (; I < V.size(); ++I) {
                    if (V[I] == '(')
                        ++Depth;
                    else if (V[I] == ')') {
                        --Depth;
                        if (Depth == 0)
                            break;
                    }
                }
                if (I >= V.size())
                    break;
                const size_t B = V.find_first_not_of(" \t\r\n", Open + 1);
                const size_t E = V.find_last_not_of(" \t\r\n", I - 1);
                if (B == MString::npos || E == MString::npos || E < B)
                    break;
                V         = V.substr(B, E - B + 1);
                bStripped = true;
            }
            return V;
        }

        // 存活变量声明去类型：`int Total = ...` → `Total = ...`（写回 Frame 槽）。
        // Start/Resume 的代码段里，跨 await 存活变量的声明若保留类型前缀会变成
        // 局部变量（遮蔽 Frame 槽，槽永远拿不到值）——去掉类型前缀即槽赋值。
        MString StripLiveDeclTypes(const MString& Code, const TVector<mession::headercodegen::SLiveVarDecl>& Live) const {
            MString Out = Code;
            for (const auto& L : Live) {
                if (L.Type.CanonicalName.empty())
                    continue;
                const MString Decl = L.Type.CanonicalName + " " + L.Name;
                size_t        Pos  = 0;
                while ((Pos = Out.find(Decl, Pos)) != MString::npos) {
                    const size_t After = Pos + Decl.size();
                    if (After >= Out.size() || Out[After] == '=' || Out[After] == ';' || Out[After] == ' ') {
                        Out = Out.substr(0, Pos) + L.Name + Out.substr(After);
                        Pos += L.Name.size();
                    } else {
                        Pos = After;
                    }
                }
            }
            return Out;
        }

        // ============ 通用递归控制流生成器（N 层嵌套/循环/组合） ============
        // 生成"执行 Nodes[start..] 的代码"（递归）。Return → Finish+return；
        // For → 循环进入（方法单独生成）；Await → 挂起/同步继续。
        void GenCFExec(const TVector<CFlowNode>& Nodes, size_t Start, MString& Out, const MString& Indent, const mession::headercodegen::SParsedFunction& Func) const {
            const MString RespType = RFromReturnType(Func.ReturnType.CanonicalName);
            for (size_t i = Start; i < Nodes.size(); ++i) {
                const CFlowNode& N = Nodes[i];
                switch (N.Kind) {
                case CFlowNode::EKind::Raw: {
                    // `int A =`（await 语句的赋值前缀——被 TAwaitable 截断）——跳过
                    const MString RawTrim = TrimText(N.Text);
                    if (!RawTrim.empty() && RawTrim.back() == '=') {
                        break;
                    }
                    Out += Indent + StripLiveDeclTypes(N.Text, Func.LiveAcrossAwait) + ";\n";
                    break;
                }
                case CFlowNode::EKind::Return:
                    Out += Indent + "ReturnValue = " + StripValueWrapper(N.Text) + ";\n";
                    Out += Indent + "Finish();\n";
                    Out += Indent + "return;\n";
                    return;
                case CFlowNode::EKind::Await: {
                    Out += Indent + "Awaiter1 = " + MakeAwaitCall(N.F, N.Obj, N.Args, N.bMember) + ".AsAwaiter();\n";
                    Out += Indent + "if (Awaiter1->AwaitReady())\n";
                    Out += Indent + "{\n";
                    Out += Indent + "    try\n";
                    Out += Indent + "    {\n";
                    if (!N.AssignVar.empty()) {
                        Out += Indent + "        " + N.AssignVar + " = Awaiter1->AwaitResume();\n";
                    } else if (!N.LAccumPrefix.empty()) {
                        Out += Indent + "        " + N.LAccumPrefix + "Awaiter1->AwaitResume();\n";
                    } else {
                        Out += Indent + "        AwaitResult = Awaiter1->AwaitResume();\n";
                    }
                    if (N.bIsReturnAwait) {
                        // return await：结果直接作为返回值，函数结束
                        Out += Indent + "        ReturnValue = AwaitResult;\n";
                        Out += Indent + "        Finish();\n";
                        Out += Indent + "        return;\n";
                    } else {
                        GenCFExec(Nodes, i + 1, Out, Indent + "        ", Func);
                    }
                    Out += Indent + "    }\n";
                    Out += Indent + "    catch (const FFutureResultError& E)\n";
                    Out += Indent + "    {\n";
                    Out += Indent + "        Promise.SetValue(TResult<" + RespType + ", FAppError>::Err(E.GetError()));\n";
                    Out += Indent + "        SelfGuard.reset();\n";
                    Out += Indent + "        return;\n";
                    Out += Indent + "    }\n";
                    Out += Indent + "}\n";
                    Out += Indent + "else\n";
                    Out += Indent + "{\n";
                    Out += Indent + "    State = " + std::to_string(N.AwaitIndex + 1) + ";\n";
                    Out += Indent + "    SelfGuard = shared_from_this();\n";
                    Out += Indent + "    Awaiter1->AwaitSuspend(this);\n";
                    Out += Indent + "}\n";
                    return;
                }
                case CFlowNode::EKind::If: {
                    Out += Indent + "if (" + N.Text + ")\n";
                    if (!N.Children.empty()) {
                        Out += Indent + "{\n";
                        GenCFExec(N.Children[0].Children, 0, Out, Indent + "    ", Func);
                        Out += Indent + "}\n";
                    } else {
                        Out += Indent + "{}\n";
                    }
                    if (N.bHasElse && N.Children.size() >= 2) {
                        Out += Indent + "else\n";
                        Out += Indent + "{\n";
                        GenCFExec(N.Children[1].Children, 0, Out, Indent + "    ", Func);
                        Out += Indent + "}\n";
                    }
                    break;
                }
                case CFlowNode::EKind::For: {
                    // 循环进入
                    if (!N.LInit.empty()) {
                        Out += Indent + StripLiveDeclTypes(N.LInit + ";", Func.LiveAcrossAwait) + "\n";
                    }
                    Out += Indent + "LoopEntry_" + std::to_string(N.LoopIndex) + "();\n";
                    return; // For 后节点由 LoopEntry 的 false 分支（GenCFExec 剩余）处理
                }
                default:
                    break;
                }
            }
        }

        // 生成循环方法（LoopEntry_N / LoopAdvance_N）——递归遍历树，For 在
        // Nodes[i] 时 false 分支执行 Nodes[i+1..]（循环后剩余）。
        void GenCFLoopMethods(const TVector<CFlowNode>& Nodes, MString& Out, const mession::headercodegen::SParsedFunction& Func) const {
            for (size_t i = 0; i < Nodes.size(); ++i) {
                const CFlowNode& N = Nodes[i];
                switch (N.Kind) {
                case CFlowNode::EKind::For: {
                    const MString LE = "LoopEntry_" + std::to_string(N.LoopIndex);
                    const MString LA = "LoopAdvance_" + std::to_string(N.LoopIndex);
                    Out += "    void " + LE + "()\n";
                    Out += "    {\n";
                    Out += "        if (" + N.LCond + ")\n";
                    Out += "        {\n";
                    // 循环体（含 await——挂起 State）
                    if (!N.Children.empty()) {
                        GenCFExec(N.Children[0].Children, 0, Out, "            ", Func);
                    }
                    Out += "            " + LA + "();\n";
                    Out += "        }\n";
                    Out += "        else\n";
                    Out += "        {\n";
                    // 循环后剩余（Nodes[i+1..]）
                    GenCFExec(Nodes, i + 1, Out, "            ", Func);
                    if (i + 1 >= Nodes.size()) {
                        Out += "            return;\n"; // 循环是块尾——Finish 由上层/return 处理
                    }
                    Out += "        }\n";
                    Out += "    }\n";
                    Out += "\n";
                    Out += "    void " + LA + "()\n";
                    Out += "    {\n";
                    Out += "        " + N.LIncr + ";\n";
                    Out += "        " + LE + "();\n";
                    Out += "    }\n";
                    Out += "\n";
                    // 递归 body（嵌套循环）
                    if (!N.Children.empty()) {
                        GenCFLoopMethods(N.Children[0].Children, Out, Func);
                    }
                    break;
                }
                case CFlowNode::EKind::If:
                    for (const auto& C : N.Children) {
                        GenCFLoopMethods(C.Children, Out, Func);
                    }
                    break;
                default:
                    break;
                }
            }
        }

        // 生成通用递归控制流 Frame（N 层嵌套/循环/组合）。
        MString EmitAwaitCFrame(const MString& NamePrefix, const fs::path& HeaderPath, const mession::headercodegen::SParsedFunction& Func) const {
            (void)HeaderPath;
            if (Func.AsyncBody.empty())
                return {};
            // 剥离函数体外层大括号（{ ... }）
            MString Body = StripComments(Func.AsyncBody);
            {
                const size_t B1 = Body.find_first_not_of(" \t\r\n");
                const size_t B2 = Body.find_last_not_of(" \t\r\n");
                if (B1 != MString::npos && Body[B1] == '{' && B2 != MString::npos && Body[B2] == '}') {
                    Body = Body.substr(B1 + 1, B2 - B1 - 1);
                }
            }
            // 1. 解析控制流树
            size_t             SiteIdx = 0, EndPos = 0;
            TVector<CFlowNode> Top;
            if (!ParseControlFlow(Body, Func.AwaitSites, SiteIdx, Top, EndPos)) {
                return {};
            }
            size_t LoopCounter = 0;
            {
                // 递归遍历（用简单 lambda——生成器内）
                std::function<void(TVector<CFlowNode>&)> AssignLoops = [&](TVector<CFlowNode>& Ns) {
                    for (auto& N : Ns) {
                        if (N.Kind == CFlowNode::EKind::For) {
                            N.LoopIndex = LoopCounter++;
                            if (!N.Children.empty())
                                AssignLoops(N.Children[0].Children);
                        } else if (N.Kind == CFlowNode::EKind::If) {
                            for (auto& C : N.Children)
                                AssignLoops(C.Children);
                        }
                    }
                };
                AssignLoops(Top);
            }
            const MString FrameName = "MHeaderTool_AwaitFrame_" + SanitizeIdentifier(NamePrefix) + "_" + SanitizeIdentifier(Func.Name);
            const MString R         = RFromReturnType(Func.ReturnType.CanonicalName);
            if (R.empty())
                return {};

            std::ostringstream Out;
            Out << "// " << FrameName << ": 通用递归控制流 await Frame\n";
            Out << "struct " << FrameName << " : TEnableSharedFromThis<" << FrameName << ">\n";
            Out << "{\n";
            for (const auto& P : Func.Params) {
                Out << "    " << P.Type.CanonicalName << " " << P.Name << "{};\n";
            }
            bool bHasLive = false;
            for (const auto& L : Func.LiveAcrossAwait) {
                if (!bHasLive) {
                    Out << "    // 跨 await 存活变量\n";
                    bHasLive = true;
                }
                Out << "    " << L.Type.CanonicalName << " " << L.Name << "{};\n";
            }
            // await 结果变量 / 累加变量 / 循环变量：跨挂起需要 Frame 槽
            //（await 结果即使不"跨多个 await"——Start 挂起后 Resume 也要用）
            {
                TVector<MString>                               ExtraVars;
                std::function<void(const TVector<CFlowNode>&)> CollectVars = [&](const TVector<CFlowNode>& Ns) {
                    for (const auto& N : Ns) {
                        if (N.Kind == CFlowNode::EKind::Await) {
                            if (!N.AssignVar.empty())
                                ExtraVars.push_back(N.AssignVar);
                            if (!N.LAccumPrefix.empty()) {
                                // `Sum += ` → Sum
                                const size_t OpPos = N.LAccumPrefix.find("+=");
                                const size_t E     = OpPos == MString::npos ? N.LAccumPrefix.size() : OpPos;
                                MString      V     = TrimText(N.LAccumPrefix.substr(0, E));
                                if (!V.empty())
                                    ExtraVars.push_back(V);
                            }
                        } else if (N.Kind == CFlowNode::EKind::For) {
                            // `int i = 0` → i
                            const size_t Eq = N.LInit.find('=');
                            if (Eq != MString::npos) {
                                const size_t EndV = N.LInit.find_last_not_of(" \t", Eq - 1);
                                if (EndV != MString::npos) {
                                    const size_t StartV = N.LInit.find_last_of(" \t", EndV);
                                    ExtraVars.push_back(N.LInit.substr(StartV == MString::npos ? 0 : StartV + 1, EndV - (StartV == MString::npos ? 0 : StartV + 1) + 1));
                                }
                            }
                            if (!N.Children.empty())
                                CollectVars(N.Children[0].Children);
                        } else if (N.Kind == CFlowNode::EKind::If) {
                            for (const auto& C : N.Children)
                                CollectVars(C.Children);
                        }
                    }
                };
                CollectVars(Top);
                for (const auto& V : ExtraVars) {
                    bool bInLive = false;
                    for (const auto& L : Func.LiveAcrossAwait) {
                        if (L.Name == V) {
                            bInLive = true;
                            break;
                        }
                    }
                    if (bInLive)
                        continue;
                    bool bDup = false;
                    for (const auto& D : ExtraVars) {
                        // 简单去重（同类变量）
                        (void)D;
                    }
                    if (!bHasLive) {
                        Out << "    // 跨 await 存活变量\n";
                        bHasLive = true;
                    }
                    Out << "    " << R << " " << V << "{};\n";
                }
            }
            Out << "    " << R << " ReturnValue{};\n";
            Out << "    TOptional<SFutureResult<" << R << ">::SAwaiter> Awaiter1;\n";
            if (R != "void") {
                Out << "    " << R << " AwaitResult{};\n";
            }
            Out << "    TSharedPtr<" << FrameName << "> SelfGuard;  // 挂起期间持有自己（完成时释放）\n";
            Out << "    MPromise<TResult<" << R << ", FAppError>> Promise;\n";
            Out << "    int State = 0;\n";
            Out << "\n";
            Out << "    void Start()\n";
            Out << "    {\n";
            MString StartBody;
            GenCFExec(Top, 0, StartBody, "        ", Func);
            Out << StartBody;
            // Start 末尾：若未 Finish（fall-through）——默认值
            if (StartBody.find("Finish();") == MString::npos) {
                Out << "        ReturnValue = " << R << "{};\n";
                Out << "        Finish();\n";
            }
            Out << "    }\n";
            Out << "\n";
            // 循环方法
            MString LoopMethods;
            GenCFLoopMethods(Top, LoopMethods, Func);
            Out << LoopMethods;
            // Resume：每个 await 一个 case（恢复块 = await 后同列表剩余 + 循环收尾）
            Out << "    void Resume()\n";
            Out << "    {\n";
            Out << "        switch (State)\n";
            Out << "        {\n";
            // 收集 await 的"同列表剩余"（遍历树）
            // 简化：Resume case K = 该 await 所在列表的后续节点（GenCFExec）
            std::function<void(const TVector<CFlowNode>&, TVector<CFlowNode>&)> CollectResumes = [&](const TVector<CFlowNode>& Ns, TVector<CFlowNode>& CollectOut) {
                for (size_t i = 0; i < Ns.size(); ++i) {
                    const CFlowNode& N = Ns[i];
                    if (N.Kind == CFlowNode::EKind::Await) {
                        // 记录该 await 后的剩余
                        // （Resume case 用——GenCFExec(Ns, i+1)）
                        // 存储为"节点列表指针+位置"太复杂——直接生成时递归处理：
                        // 用 map：AwaitIndex → (Ns 引用, i+1)？——引用不稳定。
                        // 方案：Resume case K 直接调用 GenCFExec（生成时遍历树找到位置）。
                        // 这里记录"该 await 所在列表"——用副本（小规模可接受）。
                        CollectOut.push_back(N); // placeholder——实际在生成 case 时处理
                    }
                    if (N.Kind == CFlowNode::EKind::If) {
                        for (const auto& C : N.Children)
                            CollectResumes(C.Children, CollectOut);
                    } else if (N.Kind == CFlowNode::EKind::For && !N.Children.empty()) {
                        CollectResumes(N.Children[0].Children, CollectOut);
                    }
                }
            };
            TVector<CFlowNode> CollectDummy;
            CollectResumes(Top, CollectDummy);
            // 生成 case：遍历树，对每个 Await 生成恢复块（GenCFExec 该 await 后同列表剩余）
            // GenCases：为每个 await 生成 Resume case。Tail = 当前块执行完后的
            // 继续（fall-through：if 块无 return → 外层；或循环收尾 LoopAdvance）。
            std::function<void(const TVector<CFlowNode>&, size_t, bool, const TVector<CFlowNode>&, size_t)> GenCases = [&](const TVector<CFlowNode>& Ns, size_t ParentLoop, bool bInLoop, const TVector<CFlowNode>& TailNs, size_t TailStart) {
                for (size_t i = 0; i < Ns.size(); ++i) {
                    const CFlowNode& N = Ns[i];
                    if (N.Kind == CFlowNode::EKind::Await) {
                        const size_t K = N.AwaitIndex;
                        Out << "        case " << (K + 1) << ":  // await " << (K + 1) << " 完成\n";
                        Out << "        {\n";
                        if (N.bIsReturnAwait) {
                            // return await：恢复后直接作为返回值，函数结束
                            Out << "            ReturnValue = Awaiter1->AwaitResume();\n";
                            Out << "            Finish();\n";
                            Out << "            break;\n";
                            Out << "        }\n";
                            continue;
                        }
                        MString Rest;
                        GenCFExec(Ns, i + 1, Rest, "            ", Func);
                        // fall-through：await 后同列表无剩余 → 继续尾随（外层/循环收尾）
                        if (i + 1 >= Ns.size()) {
                            GenCFExec(TailNs, TailStart, Rest, "            ", Func);
                        }
                        Out << Rest;
                        // 循环体 await 恢复 → 循环收尾（LoopAdvance）——return 已返回则不追加
                        if (bInLoop && Rest.find("return;") == MString::npos && Rest.find("Finish();") == MString::npos) {
                            Out << "            LoopAdvance_" << ParentLoop << "();\n";
                        } else if (Rest.empty()) {
                            Out << "            ReturnValue = " << R << "{};\n";
                            Out << "            Finish();\n";
                        }
                        Out << "            break;\n";
                        Out << "        }\n";
                    }
                    if (N.Kind == CFlowNode::EKind::If) {
                        // 分支块的尾随 = if 后的同列表剩余 + 外层尾随（fall-through）
                        TVector<CFlowNode> MergedTail;
                        for (size_t j = i + 1; j < Ns.size(); ++j)
                            MergedTail.push_back(Ns[j]);
                        for (size_t j = TailStart; j < TailNs.size(); ++j)
                            MergedTail.push_back(TailNs[j]);
                        for (size_t ci = 0; ci < N.Children.size(); ++ci) {
                            GenCases(N.Children[ci].Children, ParentLoop, bInLoop, MergedTail, 0);
                        }
                    } else if (N.Kind == CFlowNode::EKind::For && !N.Children.empty()) {
                        // 循环体尾随 = LoopAdvance（循环收尾，不 fall-through 外层）
                        GenCases(N.Children[0].Children, N.LoopIndex, true, TVector<CFlowNode>(), 0);
                    }
                }
            };
            TVector<CFlowNode> EmptyTail;
            GenCases(Top, 0, false, EmptyTail, 0);
            Out << "        default: break;\n";
            Out << "        }\n";
            Out << "    }\n";
            Out << "\n";
            Out << "    void Finish()\n";
            Out << "    {\n";
            Out << "        Promise.SetValue(TResult<" << R << ", FAppError>::Ok(ReturnValue));\n";
            Out << "        SelfGuard.reset();\n";
            Out << "    }\n";
            Out << "\n";
            Out << "    SFutureResult<" << R << "> GetFuture()\n";
            Out << "    {\n";
            Out << "        return SFutureResult<" << R << ">(Promise.GetFuture());\n";
            Out << "    }\n";
            Out << "};\n";
            return Out.str();
        }

        // 消费 IR 原生类型——AwaitSites/LiveAcrossAwait 只在 IR SParsedFunction 上。
        MString EmitAwaitStateMachineFrame(const MString& NamePrefix, const fs::path& HeaderPath, const mession::headercodegen::SParsedFunction& Func) const {
            (void)HeaderPath;
            // 收集全部 TAwaitable 站点（按行排序 = 源码顺序）
            TVector<const mession::headercodegen::SAwaitSite*> Sites;
            for (const auto& S : Func.AwaitSites) {
                if (S.Kind == mession::headercodegen::EAwaitSiteKind::TAwaitableCall) {
                    Sites.push_back(&S);
                }
            }
            if (Sites.empty())
                return {};
            // 通用递归控制流（N 层嵌套/循环/组合）——含 if/for 时的唯一路径
            //（分支/循环特化已被通用接管；解析失败宁缺毋滥——不生成坏产物）。
            if (Func.AsyncBody.find("if (") != MString::npos || Func.AsyncBody.find("for (") != MString::npos) {
                return EmitAwaitCFrame(NamePrefix, HeaderPath, Func);
            }
            std::sort(Sites.begin(), Sites.end(), [](const mession::headercodegen::SAwaitSite* A, const mession::headercodegen::SAwaitSite* B) { return A->SourceLine < B->SourceLine; });

            const size_t     N = Sites.size();
            TVector<MString> F(N), R(N), Args(N), AssignVar(N), SegCode(N), Obj(N);
            TVector<bool>    bMemberFlags(N, false);
            MString          PostReturnExpr;

            for (size_t K = 0; K < N; ++K) {
                bool    bMember = false;
                MString ObjStr;
                if (!ParseTAwaitableText(Sites[K]->AwaitExprText, F[K], R[K], Args[K], bMember, ObjStr))
                    return {};
                bMemberFlags[K] = bMember;
                Obj[K]          = std::move(ObjStr);
                if (R[K].empty())
                    R[K] = RFromReturnType(Func.ReturnType.CanonicalName);
                // 赋值变量：本 await 语句行首到 await 表达式（`int A = `）
                const size_t AwaitPos = Func.AsyncBody.find(Sites[K]->AwaitExprText);
                if (AwaitPos == MString::npos)
                    return {};
                const size_t LineStart = Func.AsyncBody.rfind('\n', AwaitPos) == MString::npos ? 0 : Func.AsyncBody.rfind('\n', AwaitPos) + 1;
                MString      Prefix    = Func.AsyncBody.substr(LineStart, AwaitPos - LineStart);
                {
                    const size_t Eq = Prefix.rfind('=');
                    if (Eq != MString::npos && Eq > 0) {
                        const size_t EndV = Prefix.find_last_not_of(" \t", Eq - 1);
                        if (EndV != MString::npos) {
                            const size_t StartV = Prefix.find_last_of(" \t", EndV);
                            AssignVar[K]        = Prefix.substr(StartV == MString::npos ? 0 : StartV + 1, EndV - (StartV == MString::npos ? 0 : StartV + 1) + 1);
                        }
                    }
                }
                // 本 await 语句结束 ';'
                const size_t StmtEnd = Func.AsyncBody.find(';', AwaitPos + Sites[K]->AwaitExprText.size());
                if (StmtEnd == MString::npos)
                    return {};
                // 段 K（await K 语句后到 await K+1 行首）——await K+1 前业务代码
                if (K + 1 < N) {
                    const size_t NextPos = Func.AsyncBody.find(Sites[K + 1]->AwaitExprText);
                    if (NextPos != MString::npos) {
                        const size_t NextLine = Func.AsyncBody.rfind('\n', NextPos) == MString::npos ? 0 : Func.AsyncBody.rfind('\n', NextPos) + 1;
                        // 段代码从下一行行首开始（跳过本行尾注释，如 `;  // await 1`）
                        const size_t SegStart = Func.AsyncBody.find('\n', StmtEnd);
                        MString      Seg      = (SegStart == MString::npos) ? MString() : Func.AsyncBody.substr(SegStart + 1, NextLine - SegStart - 1);
                        const size_t B        = Seg.find_first_not_of(" \t\r\n");
                        const size_t E        = Seg.find_last_not_of(" \t\r\n");
                        SegCode[K]            = (B == MString::npos) ? MString() : Seg.substr(B, E - B + 1);
                    }
                } else {
                    // 最后一段：'return <expr>;'
                    const size_t RetPos = Func.AsyncBody.find("return", StmtEnd);
                    if (RetPos != MString::npos) {
                        const size_t Semi = Func.AsyncBody.find(';', RetPos);
                        if (Semi != MString::npos) {
                            MString      Expr = Func.AsyncBody.substr(RetPos + 6, Semi - RetPos - 6);
                            const size_t B    = Expr.find_first_not_of(" \t\r\n");
                            const size_t E    = Expr.find_last_not_of(" \t\r\n");
                            if (B != MString::npos)
                                PostReturnExpr = Expr.substr(B, E - B + 1);
                        }
                    }
                }
            }

            const MString FrameName = "MHeaderTool_AwaitFrame_" + SanitizeIdentifier(NamePrefix) + "_" + SanitizeIdentifier(Func.Name);

            // 生成"触发 await K"块（ready 路径内联展开后续 await；缩进统一 8 空格）。
            std::function<MString(size_t, const MString&)> GenAwait = [&](size_t K, const MString& Indent) -> MString {
                const MString AN = "Awaiter" + std::to_string(K + 1);
                MString       Out;
                Out += Indent + AN + " = " + MakeAwaitCall(F[K], Obj[K], Args[K], bMemberFlags[K]) + ".AsAwaiter();  // 源码行 " + std::to_string(Sites[K]->SourceLine) + "\n";
                Out += Indent + "if (" + AN + "->AwaitReady())\n";
                Out += Indent + "{\n";
                Out += Indent + "    try\n";
                Out += Indent + "    {\n";
                if (!AssignVar[K].empty()) {
                    Out += Indent + "        " + AssignVar[K] + " = " + AN + "->AwaitResume();\n";
                } else {
                    Out += Indent + "        AwaitResult" + std::to_string(K + 1) + " = " + AN + "->AwaitResume();\n";
                }
                if (!SegCode[K].empty()) {
                    Out += Indent + "        // await " + std::to_string(K + 1) + " 完成后续业务代码\n";
                    Out += Indent + "        " + SegCode[K] + "\n";
                }
                if (K + 1 < N) {
                    Out += GenAwait(K + 1, Indent + "        ");
                } else {
                    Out += Indent + "        Finish();\n";
                }
                Out += Indent + "    }\n";
                Out += Indent + "    catch (const FFutureResultError& E)\n";
                Out += Indent + "    {\n";
                Out += Indent + "        Promise.SetValue(TResult<" + R[0] + ", FAppError>::Err(E.GetError()));\n";
                Out += Indent + "        SelfGuard.reset();\n";
                Out += Indent + "        return;\n";
                Out += Indent + "    }\n";
                Out += Indent + "}\n";
                Out += Indent + "else\n";
                Out += Indent + "{\n";
                Out += Indent + "    State = " + std::to_string(K + 1) + ";  // 等待 await " + std::to_string(K + 1) + " 完成（源码行 " + std::to_string(Sites[K]->SourceLine) + "）\n";
                Out += Indent + "    SelfGuard = shared_from_this();  // 挂起期间持有自己（完成时释放）\n";
                Out += Indent + "    " + AN + "->AwaitSuspend(this);\n";
                Out += Indent + "}\n";
                return Out;
            };

            std::ostringstream Out;
            Out << "// " << FrameName << ": await 状态机 Frame（串行, KD-9/KD-12）\n";
            Out << "struct " << FrameName << " : TEnableSharedFromThis<" << FrameName << ">\n";
            Out << "{\n";
            Out << "    // 函数参数\n";
            for (const auto& P : Func.Params) {
                Out << "    " << StripParamQualifiers(P.Type.CanonicalName) << " " << P.Name << "{};\n";
            }
            bool bHasLive = false;
            for (const auto& L : Func.LiveAcrossAwait) {
                if (!bHasLive) {
                    Out << "    // 跨 await 存活变量（Frame 持久化）\n";
                    bHasLive = true;
                }
                Out << "    " << L.Type.CanonicalName << " " << L.Name << "{};\n";
            }
            for (size_t K = 0; K < N; ++K) {
                if (AssignVar[K].empty())
                    continue;
                bool bExist = false;
                for (const auto& L : Func.LiveAcrossAwait) {
                    if (L.Name == AssignVar[K]) {
                        bExist = true;
                        break;
                    }
                }
                if (!bExist) {
                    if (!bHasLive) {
                        Out << "    // 跨 await 存活变量（Frame 持久化）\n";
                        bHasLive = true;
                    }
                    Out << "    " << R[K] << " " << AssignVar[K] << "{};\n";
                }
            }
            Out << "    // await 驱动\n";
            for (size_t K = 0; K < N; ++K) {
                Out << "    TOptional<SFutureResult<" << R[K] << ">::SAwaiter> Awaiter" << (K + 1) << ";\n";
                // 裸 await（无赋值变量）时结果暂存槽；有赋值变量时冗余但保持（简化生成）
                Out << "    " << R[K] << " AwaitResult" << (K + 1) << "{};\n";
            }
            Out << "    TSharedPtr<" << FrameName << "> SelfGuard;  // 挂起期间持有自己（完成时释放）\n";
            Out << "    MPromise<TResult<" << R[0] << ", FAppError>> Promise;\n";
            Out << "    int State = 0;  // 0=初始, K=等待第 K 个 await 完成\n";
            Out << "\n";
            Out << "    void Start()\n";
            Out << "    {\n";
            {
                // 首个 await 前代码
                const size_t FirstPos  = Func.AsyncBody.find(Sites[0]->AwaitExprText);
                const size_t FirstLine = Func.AsyncBody.rfind('\n', FirstPos) == MString::npos ? 0 : Func.AsyncBody.rfind('\n', FirstPos) + 1;
                MString      Pre       = Func.AsyncBody.substr(0, FirstLine);
                const size_t B         = Pre.find_first_not_of(" \t\r\n{");
                const size_t E         = Pre.find_last_not_of(" \t\r\n}");
                MString      PreTrim   = (B == MString::npos) ? MString() : Pre.substr(B, E - B + 1);
                if (!PreTrim.empty()) {
                    PreTrim = StripLiveDeclTypes(PreTrim, Func.LiveAcrossAwait);
                    Out << "        // await 前业务代码\n";
                    Out << "        " << PreTrim << "\n";
                }
            }
            Out << GenAwait(0, "        ");
            Out << "    }\n";
            Out << "\n";
            Out << "    void Resume()\n";
            Out << "    {\n";
            Out << "        switch (State)\n";
            Out << "        {\n";
            for (size_t K = 1; K <= N; ++K) {
                Out << "        case " << K << ":  // await " << K << " 完成（源码行 " << Sites[K - 1]->SourceLine << "）\n";
                Out << "            try\n";
                Out << "            {\n";
                if (!AssignVar[K - 1].empty()) {
                    Out << "                " << AssignVar[K - 1] << " = Awaiter" << K << "->AwaitResume();\n";
                } else {
                    Out << "                AwaitResult" << K << " = Awaiter" << K << "->AwaitResume();\n";
                }
                if (!SegCode[K - 1].empty() && K < N) {
                    Out << "                // await " << K << " 后续业务代码\n";
                    Out << "                " << StripLiveDeclTypes(SegCode[K - 1], Func.LiveAcrossAwait) << "\n";
                }
                if (K < N) {
                    Out << GenAwait(K, "                ");
                } else {
                    Out << "                Finish();\n";
                }
                Out << "            }\n";
                Out << "            catch (const FFutureResultError& E)\n";
                Out << "            {\n";
                Out << "                Promise.SetValue(TResult<" << R[0] << ", FAppError>::Err(E.GetError()));\n";
                Out << "                SelfGuard.reset();\n";
                Out << "                return;\n";
                Out << "            }\n";
                Out << "            break;\n";
            }
            Out << "        default: break;\n";
            Out << "        }\n";
            Out << "    }\n";
            Out << "\n";
            Out << "    void Finish()\n";
            Out << "    {\n";
            if (!PostReturnExpr.empty() && PostReturnExpr.find("TAwaitable<") == MString::npos) {
                Out << "        Promise.SetValue(TResult<" << R[0] << ", FAppError>::Ok(" << StripValueWrapper(PostReturnExpr) << "));\n";
            } else {
                // A 形态：`return TAwaitable<F,R>(args)`——await 结果直接作为函数返回值
                Out << "        Promise.SetValue(TResult<" << R[0] << ", FAppError>::Ok(std::move(AwaitResult" << N << ")));\n";
            }
            Out << "        SelfGuard.reset();  // 完成：释放自持有（挂起期间 Frame 存活）\n";
            Out << "    }\n";
            Out << "\n";
            Out << "    SFutureResult<" << R[0] << "> GetFuture()\n";
            Out << "    {\n";
            Out << "        return SFutureResult<" << R[0] << ">(Promise.GetFuture());\n";
            Out << "    }\n";
            Out << "};\n";
            return Out.str();
        }

        // 生成 `<Class>_AwaitStateMachine.h`（含该 Record 所有 async 函数的 await Frame）
        MString EmitAwaitStateMachineHeader(const mession::headercodegen::SParsedRecord& Record) const {
            std::ostringstream Out;
            bool               bAny = false;
            for (const auto& F : Record.Functions) {
                if (!F.bIsAsync)
                    continue;
                const MString Frame = EmitAwaitStateMachineFrame(Record.Name, Record.HeaderPath, F);
                if (!Frame.empty()) {
                    if (!bAny) {
                        Out << "#pragma once\n";
                        Out << "// Generated by MHeaderTool (await 状态机, 单 await 形态)\n";
                        Out << "// Source: " << Record.HeaderPath.string() << "\n\n";
                        Out << "#include \"Common/Runtime/Async/MAsync.h\"\n";
                        Out << "#include \"Common/Runtime/Async/Awaitable.h\"\n";
                        Out << "#include \"Common/Runtime/Concurrency/Promise.h\"\n";
                        Out << "#include <functional>  // std::invoke(成员函数 await)\n";
                        Out << "\n";
                        bAny = true;
                    }
                    Out << Frame << "\n";
                }
            }
            return bAny ? Out.str() : MString();
        }

        // 自由函数 await Frame（AsyncDemo2 形态）：按 HeaderPath 分组输出，
        // Frame 名前缀 Free（对齐 P4 EmitFreeAsyncStateMachine 命名）。
        MString EmitFreeAwaitStateMachineHeader(const TVector<mession::headercodegen::SParsedFunction>& FreeFuncs, const fs::path& HeaderPath) const {
            std::ostringstream Out;
            bool               bAny = false;
            for (const auto& F : FreeFuncs) {
                if (!F.bIsAsync)
                    continue;
                const MString Frame = EmitAwaitStateMachineFrame("Free", HeaderPath, F);
                if (!Frame.empty()) {
                    if (!bAny) {
                        Out << "#pragma once\n";
                        Out << "// Generated by MHeaderTool (await 状态机, 自由函数)\n";
                        Out << "// Source: " << HeaderPath.string() << "\n\n";
                        Out << "#include \"Common/Runtime/Async/MAsync.h\"\n";
                        Out << "#include \"Common/Runtime/Async/Awaitable.h\"\n";
                        Out << "#include \"Common/Runtime/Concurrency/Promise.h\"\n";
                        Out << "#include <functional>  // std::invoke(成员函数 await)\n";
                        Out << "\n";
                        bAny = true;
                    }
                    Out << Frame << "\n";
                }
            }
            return bAny ? Out.str() : MString();
        }

        // 生成 await 状态机驱动 函数实现（对接 await Frame）：创建 Frame → 填参数槽 → Start → GetFuture。
        // 业务头声明 + #ifdef MESSION_AWAIT_CODEGEN_SOURCE 内联体（codegen 解析用），
        // 实现生成到 .AwaitImpl.mgenerated.cpp，链接时覆盖。
        // 生成 await 状态机驱动函数实现（C# async 模型：业务逻辑体是 codegen 输入，
        // 编译版实现由此生成，含业务逻辑段——await 前代码进 Start、await 后进 Resume）。
        // 生成物自包含：include 用户头（Helper/类型声明）+ 状态机 Frame 头。
        MString EmitAwaitFuncImpl(const MString& NamePrefix, const fs::path& HeaderPath, const mession::headercodegen::SParsedFunction& Func) const {
            bool bHasAwait = false;
            for (const auto& S : Func.AwaitSites) {
                if (S.Kind == mession::headercodegen::EAwaitSiteKind::TAwaitableCall) {
                    bHasAwait = true;
                    break;
                }
            }
            if (!bHasAwait)
                return {};

            const MString FrameName  = "MHeaderTool_AwaitFrame_" + SanitizeIdentifier(NamePrefix) + "_" + SanitizeIdentifier(Func.Name);
            const MString ReturnType = Func.ReturnType.CanonicalName;

            std::ostringstream Out;
            Out << "// await 状态机驱动函数实现（codegen 生成，含业务逻辑段）\n";
            Out << ReturnType << " ";
            if (NamePrefix != "Free") {
                Out << NamePrefix << "::";
            }
            Out << Func.Name << "(";
            for (size_t I = 0; I < Func.Params.size(); ++I) {
                if (I)
                    Out << ", ";
                Out << Func.Params[I].Type.CanonicalName << " " << Func.Params[I].Name;
            }
            Out << ")\n";
            Out << "{\n";
            Out << "    auto Frame = MakeShared<" << FrameName << ">();\n";
            for (const auto& P : Func.Params) {
                Out << "    Frame->" << P.Name << " = " << P.Name << ";\n";
            }
            Out << "    Frame->Start();\n";
            Out << "    return Frame->GetFuture();\n";
            Out << "}\n";
            return Out.str();
        }

