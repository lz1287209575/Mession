/**
 * @file ScriptBindEmitter.cpp
 * @brief 把反射类里的 `MFUNCTION(ScriptBind)` 函数投影成 Lua 包装表与 Teal 类型声明。
 *
 * @detail 每个类写两个文件,都是**覆盖式**写入(同名旧文件被直接截断,不做增量):
 *   - `<Class>.lua`  :Lua 侧的 `M_<Class>` 表,每个 ScriptBind 函数体统一转调
 *                     `M.InvokeStatic("<Class>", "<Fn>", {...})`。该全局由 C 端
 *                     `MLuaBridge::Install` 注册,生成的 .lua 不 require 任何 module。
 *   - `<Class>.d.tl` :Teal record,方法签名取自 ScriptBind 函数形参,字段取自 MPROPERTY,
 *                     供 lua-language-server / Teal 做类型检查。
 *   只处理**至少含一个** ScriptBind 函数的类;其余类不产出任何文件(不会留空表)。
 *
 *   NOTE: 生成的 Lua 包装不传 self —— 运行时 `MLuaBridge::M_InvokeStatic` 每次调用都临时
 *   构造一个实例充当 self,生命周期仅覆盖本次调用。可编组的参数/返回类型是有限集合
 *   (见 MLuaBridge.cpp 的 MarshalOne / PushReturnOne):未覆盖的类型在 Teal 里退化为
 *   `any`,运行时则报 `arg_type_mismatch` / `unsupported_return_type`。
 */
#include "ScriptBindEmitter.h"
#include "Core/Types.h"

#include <fstream>
#include <sstream>

namespace MHeaderTool {

    namespace {

        /**
         * @brief 把反射类型名映射成 Teal 类型名。
         * @param CppType MFUNCTION 形参/返回类型原文,如 "int32_t"、"MString"
         * @return Teal 类型名;未覆盖的类型一律返回 "any"
         *
         * @detail 映射是**有限**的:所有定长整型(含有符号/无符号)都并入 "integer",
         *         float/double 并入 "number",void 并入 "nil"。只看类型名文本、不解析模板,
         *         所以 "SFutureResult<int>" 这类复合类型会落到 "any"。
         */
        MString MapTealType(const MString& CppType) {
            if (CppType == "int8_t" || CppType == "int16_t" || CppType == "int32_t" || CppType == "int64_t")
                return "integer";
            if (CppType == "uint8_t" || CppType == "uint16_t" || CppType == "uint32_t" || CppType == "uint64_t")
                return "integer";
            if (CppType == "float" || CppType == "double")
                return "number";
            if (CppType == "bool")
                return "boolean";
            if (CppType == "MString")
                return "string";
            if (CppType == "void")
                return "nil";
            return "any";
        }

    } // namespace

    void ScriptBindEmitter::Run(const std::filesystem::path& OutDir, const TVector<SParsedClass>& Classes) {
        std::filesystem::create_directories(OutDir);

        for (const SParsedClass& Cls : Classes) {
            // 跳过没有 ScriptBind 方法的类
            bool bHasScriptBind = false;
            for (const auto& Fn : Cls.Functions) {
                if (Fn.Transport == "ScriptBind") {
                    bHasScriptBind = true;
                    break;
                }
            }
            if (!bHasScriptBind)
                continue;

            std::filesystem::path LuaFile  = OutDir / (Cls.Name + ".lua");
            std::filesystem::path TealFile = OutDir / (Cls.Name + ".d.tl");

            // ---- 生成 .lua(Lua 侧包装表)----
            // Phase 1 只做类级静态派发:业务 Lua 写 M_TestClass.Add(2, 3),包装转调
            // M.InvokeStatic 后被桥接到 C++ 反射 NativeInvoke。
            // NOTE: 参数走 {...} 变参、个数不限;可编组类型见 MLuaBridge.cpp,不是"4 种"。
            std::ofstream Out(LuaFile);
            Out << "-- Auto-generated by MHeaderTool ScriptBindEmitter\n";
            Out << "-- Source class: " << Cls.Name << "\n";
            Out << "-- DO NOT EDIT — 改 " << Cls.Name << " 的 MFUNCTION 注解后跑 mht 重生\n";
            Out << "--\n";
            Out << "-- Runtime bridge 由 MLuaBridge::Install 提供(M.InvokeStatic 全局)\n";
            Out << "-- (Lua 端不再 require 任何 module,M_*/M 全局已由 C 端 push)\n\n";
            Out << "local M_" << Cls.Name << " = {}\n\n";

            for (const auto& Fn : Cls.Functions) {
                if (Fn.Transport != "ScriptBind")
                    continue;
                Out << "function M_" << Cls.Name << "." << Fn.Name << "(...)\n";
                Out << "    return M.InvokeStatic(\"" << Cls.Name << "\", \"" << Fn.Name << "\", {...})\n";
                Out << "end\n\n";
            }

            Out << "return M_" << Cls.Name << "\n";

            // ---- 生成 .d.tl(Teal 类型声明)----
            // record 里方法与属性并列:前者逐个 ScriptBind 函数生成,后者逐个 MPROPERTY 生成。
            std::ofstream Teal(TealFile);
            Teal << "---@meta mession\n";
            Teal << "-- Auto-generated by MHeaderTool ScriptBindEmitter (Teal type checker hint)\n";
            Teal << "local record M_" << Cls.Name << "\n";
            Teal << "    userdata\n\n";
            for (const auto& Fn : Cls.Functions) {
                if (Fn.Transport != "ScriptBind")
                    continue;
                Teal << "    " << Fn.Name << ": function(";
                bool bFirst = true;
                if (Fn.Params.empty()) {
                    Teal << "...";
                } else {
                    for (const auto& P : Fn.Params) {
                        if (!bFirst)
                            Teal << ", ";
                        Teal << P.Name << ": " << MapTealType(P.Type);
                        bFirst = false;
                    }
                }
                Teal << "): " << MapTealType(Fn.ReturnStorageType) << "\n";
            }
            for (const auto& Prop : Cls.Properties) {
                Teal << "    " << Prop.Name << ": " << MapTealType(Prop.Type) << "\n";
            }
            Teal << "end\n\n";
            Teal << "return M_" << Cls.Name << "\n";
        }
    }

} // namespace MHeaderTool