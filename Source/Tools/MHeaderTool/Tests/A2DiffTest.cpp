/**
 * @file A2DiffTest.cpp
 * @brief A2 迁移的字节级回归门:AST 路径的产物必须与旧(legacy)路径逐字节一致。
 *
 * @detail 做法:先跑一遍 IR 管线(MASTPipeline::Run + MCodeGenerator 的 IR 入口),把产物写到
 *         /tmp/a2_ir,再与不可变的旧基线 /tmp/legacy_baseline/ 逐个同名文件比对。
 *         基线是引入 AST 路径**之前**对 /root/Mession/Build/Generated/ 做的一次性拷贝:
 *         commit d0785c8 的 AST 路径已经把 Build/Generated 覆盖成 AST 产物,所以那里不再是基线。
 *
 *         判定规则:
 *           - 两侧都产出的文件 → 去掉时间戳行后必须字节相等,这是回归门(不等即 FAIL);
 *           - 只有一侧产出的文件 → 只打印、不参与判定,属于 A3 / 后续工作。
 *
 *         前置条件:基线目录需要人工先建好;缺失时只打 WARNING,测试会退化成"没有共享文件"
 *         的空跑(此时永远通过,不具备门禁意义)。SourceRoot 用的是相对路径 "Source",
 *         因此运行期 CWD 必须是仓库根。
 */

#include "AST/ASTPipeline.h"
#include "Core/Types.h"
#include "Generation/CodeGenerator.h"
#include "Util/FileUtil.h"
#include "Common/Runtime/Log/Tests/TestHarness.h"

#include <filesystem>
#include <fstream>
#include <sstream>
#include <string>
#include <vector>

namespace fs = std::filesystem;
namespace mession::headercodegen {

    /**
     * @brief 读入整个文件。
     * @param Path 文件路径
     * @return 文件全文;打不开时返回空串(调用方无法区分"空文件"与"不存在")
     */
    static MString ReadFile(const fs::path& Path) {
        std::ifstream F(Path);
        if (!F) {
            return {};
        }
        std::stringstream SS;
        SS << F.rdbuf();
        return SS.str();
    }

    /**
     * @brief 抹掉产物里的 "// Generated by MHeaderTool ..." 行,让不同时刻的两次生成可比。
     * @param InOut [in,out] 文件内容;就地把**首个**标记行删成空行(保留换行符)
     *
     * @detail 目前标记行只是字面量、还不带时间戳,所以两侧都是"删掉同一行",对比较结果没有影响;
     *         这样写是为了将来标记行注入时间戳(例如给增量构建用)时不必再改测试。
     *         只处理第一处匹配,找不到标记或标记行没有换行结尾时原样返回。
     */
    static void StripTimestamp(MString& InOut) {
        const MString Marker = "// Generated by MHeaderTool";
        const size_t  Pos    = InOut.find(Marker);
        if (Pos == MString::npos) {
            return;
        }
        const size_t End = InOut.find('\n', Pos);
        if (End == MString::npos) {
            return;
        }
        InOut.erase(Pos, End - Pos);
    }

    /**
     * @brief 对全量 IR 产物做一次 A2 回归比对,并把逐文件结果与汇总打到 stdout。
     *
     * @detail 步骤:跑管线 → 用 MCodeGenerator 为每条记录写 <Name>.mgenerated.h → 分别列出
     *         IR 侧 / 基线侧的文件名 → 求交与差 → 对共享文件名做字节比对,不行就打印首个
     *         差异位置。只有共享文件的不相等会累计成断言失败(失败一次继续跑,方便看全貌);
     *         单侧独有的文件只计数打印,不作为门禁。
     */
    TEST_CASE(A2DiffTest_FullHeaderIR) {
        // --- 1. 跑 IR 管线,产物落到 /tmp/a2_ir ----------------------------
        MHeaderTool::SOptions Options;
        Options.SourceRoot = "Source";

        const fs::path IRDir = "/tmp/a2_ir";

        std::error_code Ec;
        fs::remove_all(IRDir, Ec);
        fs::create_directories(IRDir, Ec);

        Options.OutputDir = IRDir;
        SParseIR IR       = MASTPipeline::Run(Options);

        std::printf("A2DiffTest: IR pipeline produced %zu records\n", IR.Records.size());

        MHeaderTool::MCodeGenerator CodeGen(Options);
        for (const SParsedRecord& Record : IR.Records) {
            const MString HeaderCode = CodeGen.GenerateHeaderFromIR(Record, IR.Records);
            MHeaderTool::WriteFile(IRDir / (MHeaderTool::SanitizeIdentifier(Record.Name) + ".mgenerated.h"), HeaderCode);
        }

        // --- 2. 收集 IR 侧产出的文件名 -----------------------------------------
        TVector<MString> IRSide;
        for (const auto& Entry : fs::directory_iterator(IRDir)) {
            if (!Entry.is_regular_file()) {
                continue;
            }
            IRSide.push_back(Entry.path().filename().string());
        }

        // --- 3. 收集旧基线一侧的文件名 -------------------------------------
        // /tmp/legacy_baseline/ 是引入 AST 路径之前的 Build/Generated/ 的一次性拷贝
        // (commit d0785c8 已把 Build/Generated 覆盖成 AST 产物,那里不再是有效基线)。
        // 基线缺失时打一行 WARNING,免得新 clone 的机器静默地拿空目录去比较、还"全过"。
        const fs::path LegacyDir = "/tmp/legacy_baseline";
        if (!fs::exists(LegacyDir)) {
            std::printf("A2DiffTest: WARNING legacy baseline %s does not exist; "
                        "run `cp -r /root/Mession/Build/Generated/ /tmp/legacy_baseline/` "
                        "first to establish the pre-AST reference.\n",
                        LegacyDir.c_str());
        }
        TVector<MString> LegacySide;
        if (fs::exists(LegacyDir)) {
            for (const auto& Entry : fs::directory_iterator(LegacyDir)) {
                if (!Entry.is_regular_file()) {
                    continue;
                }
                LegacySide.push_back(Entry.path().filename().string());
            }
        }

        // --- 4. 求两侧文件名的交与差 ----------------------------------------
        auto Contains = [](const TVector<MString>& V, const MString& Name) -> bool {
            for (const MString& S : V) {
                if (S == Name) {
                    return true;
                }
            }
            return false;
        };

        int NumSharedEql  = 0;
        int NumSharedNeq  = 0;
        int NumIROnly     = 0;
        int NumLegacyOnly = 0;

        std::printf("\n=== A2DiffTest per-file comparison (after StripTimestamp) ===\n");
        std::printf("%-50s  %-20s  %s\n", "Filename", "Status", "First divergence / note");
        std::printf("%-50s  %-20s  %s\n", "----------------------------------------", "--------------------", "----------------------------------------");

        // 找两侧内容首个不同的字节位置(返回 MString::npos 即前缀完全相同;调用方据此再判长度)。
        auto FirstDivergence = [](const MString& A, const MString& B) -> size_t {
            const size_t Limit = std::min(A.size(), B.size());
            for (size_t i = 0; i < Limit; ++i) {
                if (A[i] != B[i])
                    return i;
            }
            return MString::npos;
        };

        // 共享文件:只从 IR 侧遍历一次,保证每个文件只出一行结果(而不是两侧各出一行)。
        for (const MString& Name : IRSide) {
            if (!Contains(LegacySide, Name)) {
                ++NumIROnly;
                std::printf("%-50s  %-20s  %s\n", Name.c_str(), "AST_ONLY", "emitted by AST path; not in legacy baseline — A3 work");
                continue;
            }

            MString IRText     = ReadFile(IRDir / Name);
            MString StrippedIR = IRText;
            StripTimestamp(StrippedIR);

            MString LegacyText     = ReadFile(LegacyDir / Name);
            MString StrippedLegacy = LegacyText;
            StripTimestamp(StrippedLegacy);

            const bool bEqual = (StrippedIR == StrippedLegacy);
            if (bEqual) {
                ++NumSharedEql;
                std::printf("%-50s  %-20s  %s\n", Name.c_str(), "AST_EQL_LEGACY", "");
            } else {
                ++NumSharedNeq;
                const size_t DivPos = FirstDivergence(StrippedIR, StrippedLegacy);
                MString      Note =
                    (DivPos == MString::npos) ? MString("length differs (ir=") + std::to_string(StrippedIR.size()) + ", legacy=" + std::to_string(StrippedLegacy.size()) + ")" : MString("first diff at byte ") + std::to_string(DivPos);
                std::printf("%-50s  %-20s  %s\n", Name.c_str(), "AST_NEQ_LEGACY", Note.c_str());
            }

            // 共享文件上的断言就是回归门:这里**不提前 return**,差异会持续累积成多次失败,
            // 好让 RUN_TESTS 汇总出总条数,再由测试报告逐条描述每个差异。
            EXPECT_TRUE(bEqual);
        }

        // 只在基线里、AST 路径还没产出的文件:打印出来但**不**判失败 —— 属于 A3 / 后续范围。
        for (const MString& Name : LegacySide) {
            if (Contains(IRSide, Name)) {
                continue;
            }
            ++NumLegacyOnly;
            std::printf("%-50s  %-20s  %s\n", Name.c_str(), "LEGACY_ONLY", "in legacy baseline; not emitted by AST path yet");
        }

        std::printf("\n=== A2DiffTest summary ===\n");
        std::printf("  AST_EQL_LEGACY : %d\n", NumSharedEql);
        std::printf("  AST_NEQ_LEGACY : %d\n", NumSharedNeq);
        std::printf("  AST_ONLY       : %d\n", NumIROnly);
        std::printf("  LEGACY_ONLY    : %d\n", NumLegacyOnly);
        std::printf("\nAST_NEQ_LEGACY files are the regression gate. LEGACY_ONLY / AST_ONLY\n");
        std::printf("files are not gates — they exist because the AST visitor does not\n");
        std::printf("yet populate every IR field, and MCLASS / MGENERATED_BODY filtering\n");
        std::printf("for some types is incomplete. That's A3 / follow-up work; Task 9 is\n");
        std::printf("the measurement, A3 is the fix.\n");
    }

} // namespace mession::headercodegen

int main() {
    std::printf("Running A2DiffTest\n");
    mession::headercodegen::Test_A2DiffTest_FullHeaderIR();
    RUN_TESTS();
    return 0;
}
